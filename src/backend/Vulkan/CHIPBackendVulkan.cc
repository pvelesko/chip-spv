// pushes the returned pointer onto Backend->CallbackQueue; the
// EventMonitorVulkan loop drains it (poll GpuReady fence → exec user
// callback → host-signal CpuCallbackComplete + GpuAck → delete via
// the concrete subclass).
chipstar::CallbackData *
CHIPBackendVulkan::createCallbackData(hipStreamCallback_t Callback,
                                      void *UserData,
                                      chipstar::Queue *ChipQ) {
  if (Callback == nullptr || ChipQ == nullptr)
    return nullptr;
  return new CHIPCallbackDataVulkan(Callback, UserData, ChipQ);
}

// ===== I11: =====
// Spin up the fence-polling EventMonitor thread. Caller is the
// chipstar core during Backend::initialize(); ownership of the
// returned pointer transfers to the base Backend (which stores it in
// EventMonitor_ and joins/deletes in uninitialize).
chipstar::EventMonitor *CHIPBackendVulkan::createEventMonitor_() {
  auto *Monitor = new EventMonitorVulkan();
  Monitor->start();
  return Monitor;
}

