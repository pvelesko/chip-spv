void CHIPExecItemVulkan::setKernel(chipstar::Kernel *Kernel) {
  assert(Kernel && "Kernel is nullptr!");
  ChipKernel_ = static_cast<CHIPKernelVulkan *>(Kernel);
  this->ArgsSetup = false;
  const auto *Refl = ChipKernel_->getReflection();
  if (Refl != nullptr) {
    PushConstantBlob_.assign(Refl->PushConstantBlockSize, 0);
    BufferBindings_.assign(Refl->MaxDescriptorBinding + 1, VK_NULL_HANDLE);
    BufferRanges_.assign(Refl->MaxDescriptorBinding + 1, VK_WHOLE_SIZE);
    BufferOffsets_.assign(Refl->MaxDescriptorBinding + 1, 0);
  }
}

chipstar::Kernel *CHIPExecItemVulkan::getKernel() { return ChipKernel_; }

void CHIPExecItemVulkan::setupAllArgs() {
  assert(ChipKernel_ && "setupAllArgs called before setKernel");
  const auto *Refl = ChipKernel_->getReflection();
  if (Refl == nullptr)
    CHIPERR_LOG_AND_THROW("ExecItem::setupAllArgs: kernel has no reflection",
                          hipErrorLaunchFailure);
  auto *Mod = static_cast<CHIPModuleVulkan *>(ChipKernel_->getModule());
  auto *Dev = Mod->getDevice();
  auto *Ctx = Dev->getContext();

  // Build a quick lookup of which kernel-arg ordinals correspond to
  // hidden `__device__` global descriptors. The bridging pass appends
  // these after the HIP-source args; Args_[Ord] for those slots does NOT
  // hold a HIP pointer (it would be out-of-bounds of the user-supplied
  // args array). Instead, the descriptor must be sourced from the
  // module's per-symbol DeviceGlobals_ table.
  std::unordered_map<uint32_t, std::string> HiddenDGByOrd;
  for (const auto &DG : Refl->HiddenDGArgs)
    HiddenDGByOrd.emplace(static_cast<uint32_t>(DG.ArgIndex), DG.Symbol);

  for (const auto &Buf : Refl->Buffers) {
    auto HDGIt = HiddenDGByOrd.find(Buf.Ordinal);
    if (HDGIt != HiddenDGByOrd.end()) {
      // Hidden device-global descriptor. The chipstar layer also allocates
      // a buffer for this symbol via prepareDeviceVariables /
      // allocateDeviceVariablesNoLock and registers it in DevPtrToEntry_ —
      // that's the buffer hipMemcpyToSymbol writes to. Prefer it so the
      // kernel sees writes made via hipMemcpyToSymbol; fall back to the
      // compile()-time DeviceGlobals_ buffer (seeded from InitData) when
      // the chipstar buffer hasn't been allocated yet.
      const std::string &Sym = HDGIt->second;
      void *DevPtr = nullptr;
      if (chipstar::DeviceVar *Var = Mod->getGlobalVar(Sym.c_str()))
        DevPtr = Var->getDevAddr();
      if (DevPtr != nullptr) {
        const auto *Entry = Ctx->getDevPtrEntry(DevPtr);
        if (Entry != nullptr) {
          BufferBindings_[Buf.Binding] = Entry->Buffer;
          BufferRanges_[Buf.Binding] = Entry->Size;
          BufferOffsets_[Buf.Binding] = 0;
          continue;
        }
      }
      const auto *DGE = Mod->getDeviceGlobal(Sym);
      if (DGE == nullptr) {
        std::string Msg =
            "ExecItem::setupAllArgs: kernel references __device__ symbol '" +
            Sym + "' that wasn't allocated at module compile time";
        CHIPERR_LOG_AND_THROW(Msg, hipErrorInvalidDevicePointer);
      }
      BufferBindings_[Buf.Binding] = DGE->Buffer;
      BufferRanges_[Buf.Binding] = DGE->Size;
      BufferOffsets_[Buf.Binding] = 0;
      continue;
    }
    // Index Args_ in HIP source order, not the reflection (OCL) ord.
    // clspv reorders kernel args (pointers before PODs), so Buf.Ordinal
    // is post-reorder. The HIP runtime fills Args_ in source order.
    int32_t ArgsIdx =
        Buf.HipSourceIndex >= 0 ? Buf.HipSourceIndex : (int32_t)Buf.Ordinal;
    void *HipPtr = *reinterpret_cast<void **>(Args_[ArgsIdx]);
    // Range-based lookup: accept pointers into the middle of a hipMalloc'd
    // region (e.g. `kernel<<<...>>>(&Hmm[N], ...)` for managed memory). The
    // descriptor's offset is set so the kernel sees the same byte view the
    // caller had on the host pointer.
    size_t Offset = 0;
    // A null pointer argument is legal as long as the kernel never
    // dereferences it; bind a small placeholder buffer.
    if (HipPtr == nullptr)
      HipPtr = Ctx->getNullArgPlaceholder();
    const auto *Entry = Ctx->getDevPtrEntryContaining(HipPtr, Offset);
    if (Entry == nullptr) {
      std::string Msg = "ExecItem::setupAllArgs: unregistered device pointer "
                        "for kernel arg at ordinal " +
                        std::to_string(Buf.Ordinal);
      CHIPERR_LOG_AND_THROW(Msg, hipErrorInvalidDevicePointer);
    }
    // Storage buffer descriptors require offsets to be a multiple of
    // VkPhysicalDeviceLimits::minStorageBufferOffsetAlignment. Non-aligned
    // pointers escape the spike's offset-aware path and would silently
    // misbind; flag them as invalid so the failure is visible.
    if (Offset != 0) {
      const auto &Limits = Dev->getProperties().limits;
      VkDeviceSize Align = Limits.minStorageBufferOffsetAlignment;
      if (Align > 0 && (Offset % Align) != 0) {
        std::string Msg =
            "ExecItem::setupAllArgs: kernel arg pointer offset " +
            std::to_string(Offset) +
            " is not a multiple of minStorageBufferOffsetAlignment " +
            std::to_string(Align);
        CHIPERR_LOG_AND_THROW(Msg, hipErrorInvalidValue);
      }
    }
    BufferBindings_[Buf.Binding] = Entry->Buffer;
    // Range is the remaining byte count from the descriptor offset to the
    // end of the underlying buffer.
    BufferRanges_[Buf.Binding] =
        (Entry->Size > Offset) ? (Entry->Size - Offset) : 0;
    BufferOffsets_[Buf.Binding] = static_cast<VkDeviceSize>(Offset);
  }
  for (const auto &Pc : Refl->PushConst) {
    int32_t ArgsIdx =
        Pc.HipSourceIndex >= 0 ? Pc.HipSourceIndex : (int32_t)Pc.Ordinal;
    std::memcpy(PushConstantBlob_.data() + Pc.Offset, Args_[ArgsIdx], Pc.Size);
  }
  // Phase Z3 (BDA): for every recorded BDA pointer slot in the PC block,
  // the bytes just copied from the user are a raw HIP pointer (8 bytes;
  // under the native Vulkan backend, the VmaAllocation cookie returned by
  // hipMalloc). The BDA path in the bridging pass emits
  //   OpConvertUToPtr(_ptr_PhysicalStorageBuffer_*, <ulong>)
  // so the shader needs an actual VkDeviceAddress in those 8 bytes. Look up
  // the backing VkBuffer (range-aware to handle pointer-into-allocation),
  // resolve its device address, and overwrite the slot. Buffers were given
  // VK_BUFFER_USAGE_SHADER_DEVICE_ADDRESS_BIT at allocate time, and the
  // logical device was created with VkPhysicalDeviceVulkan12Features::
  // bufferDeviceAddress=VK_TRUE, so vkGetBufferDeviceAddress is valid here.
  if (!Refl->BDAPointerSlotOffsets.empty()) {
    if (!Dev->hasBufferDeviceAddress())
      CHIPERR_LOG_AND_THROW(
          "ExecItem::setupAllArgs: kernel uses Buffer Device Address but the "
          "Vulkan device does not support bufferDeviceAddress",
          hipErrorNotSupported);
    VkDevice VkDev = Dev->getLogicalDevice();
    for (uint32_t Offset : Refl->BDAPointerSlotOffsets) {
      if ((size_t)Offset + sizeof(uint64_t) > PushConstantBlob_.size()) {
        std::string Msg = "ExecItem::setupAllArgs: BDA pointer slot offset " +
                          std::to_string(Offset) +
                          " is past the end of the push-constant block (" +
                          std::to_string(PushConstantBlob_.size()) + " bytes)";
        CHIPERR_LOG_AND_THROW(Msg, hipErrorInvalidValue);
      }
      void *HipPtr = nullptr;
      std::memcpy(&HipPtr, PushConstantBlob_.data() + Offset, sizeof(void *));
      uint64_t Bda = 0;
      if (HipPtr != nullptr) {
        size_t SubOffset = 0;
        const auto *Entry = Ctx->getDevPtrEntryContaining(HipPtr, SubOffset);
        if (Entry == nullptr) {
          std::string Msg =
              "ExecItem::setupAllArgs: BDA pointer slot at offset " +
              std::to_string(Offset) +
              " references an unregistered device pointer";
          CHIPERR_LOG_AND_THROW(Msg, hipErrorInvalidDevicePointer);
        }
        VkBufferDeviceAddressInfo Bdai{};
        Bdai.sType = VK_STRUCTURE_TYPE_BUFFER_DEVICE_ADDRESS_INFO;
        Bdai.buffer = Entry->Buffer;
        Bda = vkGetBufferDeviceAddress(VkDev, &Bdai) + SubOffset;
      }
      std::memcpy(PushConstantBlob_.data() + Offset, &Bda, sizeof(uint64_t));
    }
  }
  this->ArgsSetup = true;
}

