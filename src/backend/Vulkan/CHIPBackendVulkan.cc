/// Active-poll loop modeled after CHIPEventMonitorLevel0::monitor() at
/// src/backend/Level0/CHIPBackendLevel0.cc:745. Vulkan has no async
/// completion notification (the closest analogue is vkWaitForFences with a
/// timeout), so the monitor sleeps for a short interval and then drains
/// state machine progress on the main thread's behalf.
///
/// Each tick:
///   1. Sleep 200us so we don't spin and burn CPU.
///   2. Walk Backend->Events and call updateFinishStatus(false) on every
///      event still in RECORDING. updateFinishStatus is implemented (by I5)
///      via a non-blocking vkGetFenceStatus poll, so this never blocks.
///   3. Drain Backend->CallbackQueue: pop one entry; if its GpuReady event
///      is now RECORDED invoke the user callback and release; otherwise
///      re-enqueue it for the next tick.
///   4. Recycle: erase any tracked, non-user event from Backend->Events
///      whose DependsOnList is empty and which has reached RECORDED.
///      Mirrors CHIPContextLevel0::checkEvents() at line 960.
///   5. If Stop is set, exit the thread cleanly.
void EventMonitorVulkan::monitor() {
  logTrace("EventMonitorVulkan::monitor() started");
  while (true) {
    std::this_thread::sleep_for(std::chrono::microseconds(200));

    // Step 2: Poll all RECORDING events for fence completion. Non-blocking;
    // updateFinishStatus(false) does not throw when the event is still
    // pending. Use try_to_lock to avoid stalling the main thread when it is
    // already mutating Events (e.g. trackEvent/erase paths).
    {
      std::unique_lock<std::mutex> Lock(Backend->EventsMtx, std::try_to_lock);
      if (Lock.owns_lock()) {
        for (auto &Ev : Backend->Events) {
          if (!Ev)
            continue;
          if (Ev->getEventStatus() == EVENT_STATUS_RECORDED)
            continue;
          LOCK(Ev->EventMtx);
          Ev->updateFinishStatus(false);
        }
      }
    }

    // Step 3: Drain every ready callback per tick. Tests like
    // Unit_hipStreamAddCallback_MultipleThreads enqueue ~1000 callbacks
    // back-to-back; a one-per-200us drain rate cannot keep up before
    // hipStreamSynchronize returns and the test exits.
    {
      std::vector<chipstar::CallbackData *> ToExecute;
      {
        LOCK(Backend->CallbackQueueMtx);
        size_t Pending = Backend->CallbackQueue.size();
        for (size_t i = 0; i < Pending; ++i) {
          chipstar::CallbackData *CbData = Backend->CallbackQueue.front();
          Backend->CallbackQueue.pop();
          bool Ready = false;
          if (CbData && CbData->GpuReady) {
            LOCK(CbData->GpuReady->EventMtx);
            CbData->GpuReady->updateFinishStatus(false);
            Ready = (CbData->GpuReady->getEventStatus() ==
                     EVENT_STATUS_RECORDED);
          } else if (CbData) {
            // No GpuReady event attached: treat as immediately ready.
            Ready = true;
          }
          if (CbData && Ready) {
            ToExecute.push_back(CbData);
          } else if (CbData) {
            // Rotate to the back; retry on the next tick.
            Backend->CallbackQueue.push(CbData);
          }
        }
      }
      // Execute outside the lock so user callbacks that call into HIP
      // (e.g. hipStreamAddCallback recursion) don't deadlock on
      // CallbackQueueMtx.
      for (auto *CbData : ToExecute) {
        InCallbackThread = true;
        CbData->execute(hipSuccess);
        InCallbackThread = false;
        if (CbData->CpuCallbackComplete)
          CbData->CpuCallbackComplete->hostSignal();
        if (CbData->GpuAck)
          CbData->GpuAck->hostSignal();
        auto *Q = static_cast<CHIPQueueVulkan *>(CbData->ChipQueue);
        delete static_cast<CHIPCallbackDataVulkan *>(CbData);
        Q->PendingCallbacks--;
      }
    }

    // Step 4: Recycle finished, dependency-free, tracked events out of
    // Backend->Events. Identical liveness criteria to
    // CHIPContextLevel0::checkEvents(): RECORDED + DependsOnList empty +
    // not a user event. User events live until hipEventDestroy.
    {
      std::unique_lock<std::mutex> Lock(Backend->EventsMtx, std::try_to_lock);
      if (Lock.owns_lock()) {
        auto NewEnd = std::remove_if(
            Backend->Events.begin(), Backend->Events.end(),
            [](const std::shared_ptr<chipstar::Event> &Ev) {
              if (!Ev)
                return true;
              if (Ev->isUserEvent())
                return false;
              if (Ev->getEventStatus() != EVENT_STATUS_RECORDED)
                return false;
              LOCK(Ev->DependsOnListMtx);
              return Ev->DependsOnList.empty();
            });
        Backend->Events.erase(NewEnd, Backend->Events.end());
      }
    }

    // Step 5: Honor Stop. Lock EventMonitorMtx so a concurrent stop() in the
    // main thread (which holds the same mutex around setting Stop and
    // joining) sees us fully outside the work above before it can read
    // Stop==true and join.
    {
      LOCK(EventMonitorMtx); // chipstar::EventMonitor::Stop
      if (Stop) {
        logTrace("EventMonitorVulkan::monitor() exiting on Stop");
        return;
      }
    }
  }
}

