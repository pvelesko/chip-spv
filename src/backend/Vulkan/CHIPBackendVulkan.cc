void *CHIPContextVulkan::allocateImpl(size_t Size, size_t Alignment,
                                      hipMemoryType MemType,
                                      chipstar::HostAllocFlags Flags) {
  LOCK(ContextMtx); // CHIPContextVulkan::DevPtrToEntry_

  CHIPDeviceVulkan *Dev = getVulkanDevice();
  if (!Dev)
    CHIPERR_LOG_AND_THROW("CHIPContextVulkan::allocateImpl: no device bound "
                          "to context",
                          hipErrorInvalidContext);
  VmaAllocator Allocator = Dev->getAllocator();
  if (Allocator == VK_NULL_HANDLE)
    CHIPERR_LOG_AND_THROW("CHIPContextVulkan::allocateImpl: VMA allocator is "
                          "not initialized (I1 owns construction)",
                          hipErrorInvalidContext);

  // Buffer usage common to every HIP allocation: the buffer must be usable as
  // a kernel-side StorageBuffer descriptor and as both source/destination of
  // vkCmdCopyBuffer transfers driven by the H2D / D2H memcpy paths in I8.
  VkBufferCreateInfo BufInfo{};
  BufInfo.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
  BufInfo.size = Size;
  BufInfo.usage = VK_BUFFER_USAGE_STORAGE_BUFFER_BIT |
                  VK_BUFFER_USAGE_TRANSFER_SRC_BIT |
                  VK_BUFFER_USAGE_TRANSFER_DST_BIT;
  // Phase Z3: opt every HIP-allocated buffer into BDA so a kernel that picks
  // the BDA path can produce a valid PhysicalStorageBuffer pointer via
  // vkGetBufferDeviceAddress. The buffer-usage bit is harmless for buffers
  // that never get queried for a device address.
  if (Dev->hasBufferDeviceAddress())
    BufInfo.usage |= VK_BUFFER_USAGE_SHADER_DEVICE_ADDRESS_BIT;
  BufInfo.sharingMode = VK_SHARING_MODE_EXCLUSIVE;

  VmaAllocationCreateInfo AllocInfo{};
  // Honor caller-supplied minimum alignment. VMA already consults the buffer's
  // memory requirements, so this only widens the constraint when the caller
  // asks for tighter alignment than Vulkan would have demanded.
  // HIP guarantees 256-byte aligned device allocations.
  AllocInfo.minAlignment =
      std::max<VkDeviceSize>(static_cast<VkDeviceSize>(Alignment), 256);
  AllocInfo.pUserData = nullptr;

  // HostAllocFlags differentiates write-combined / portable / non-coherent
  // for the spike we don't specialise the VMA path on these — the host /
  // unified branches already pick HOST_VISIBLE | HOST_COHERENT, which is the
  // safest default for HIP semantics.
  (void)Flags;

  // Synthetic-pointer strategy: for device-only allocations the VkBuffer's
  // memory is NOT host-visible, so we can't hand the caller a real CPU
  // address. We instead cast the VmaAllocation handle (an opaque pointer
  // unique per live allocation) to void* and use that as the HIP pointer.
  // The pointer is opaque to the caller; any attempt to dereference it on
  // the host will trap. For host / unified allocations the VMA-mapped
  // pointer (pMappedData) IS the HIP pointer and host dereference works.
  void *RetPtr = nullptr;
  VkBuffer Buffer = VK_NULL_HANDLE;
  VmaAllocation Allocation = VK_NULL_HANDLE;
  VmaAllocationInfo AllocResult{};
  VkResult Status = VK_ERROR_UNKNOWN;

  switch (MemType) {
  case hipMemoryTypeDevice: {
    // GPU-only: device-local, no host visibility. The HIP pointer is a
    // synthetic cookie (the VmaAllocation handle), looked up via
    // DevPtrToEntry_ at memcpy / descriptor-set bind time.
    AllocInfo.usage = VMA_MEMORY_USAGE_GPU_ONLY;
    AllocInfo.requiredFlags = VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT;
    Status = vmaCreateBuffer(Allocator, &BufInfo, &AllocInfo, &Buffer,
                             &Allocation, &AllocResult);
    if (Status != VK_SUCCESS || Allocation == VK_NULL_HANDLE)
      CHIPERR_LOG_AND_THROW("vmaCreateBuffer (device) failed",
                            hipErrorOutOfMemory);
    RetPtr = static_cast<void *>(Allocation);
    // Use the real GPU address so pointers stored in device memory work.
    if (Dev->hasBufferDeviceAddress()) {
      VkBufferDeviceAddressInfo Bdai{};
      Bdai.sType = VK_STRUCTURE_TYPE_BUFFER_DEVICE_ADDRESS_INFO;
      Bdai.buffer = Buffer;
      RetPtr = reinterpret_cast<void *>(
          vkGetBufferDeviceAddress(Dev->getLogicalDevice(), &Bdai));
    }
    break;
  }
  case hipMemoryTypeHost: {
    // Host-pinned: host-visible + host-coherent, GPU-readable via the same
    // VkBuffer. VMA persistently maps the allocation so pMappedData is the
    // HIP pointer.
    AllocInfo.usage = VMA_MEMORY_USAGE_CPU_TO_GPU;
    AllocInfo.requiredFlags = VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT |
                              VK_MEMORY_PROPERTY_HOST_COHERENT_BIT;
    AllocInfo.flags = VMA_ALLOCATION_CREATE_MAPPED_BIT;
    Status = vmaCreateBuffer(Allocator, &BufInfo, &AllocInfo, &Buffer,
                             &Allocation, &AllocResult);
    if (Status != VK_SUCCESS || Allocation == VK_NULL_HANDLE ||
        AllocResult.pMappedData == nullptr)
      CHIPERR_LOG_AND_THROW("vmaCreateBuffer (host) failed",
                            hipErrorOutOfMemory);
    RetPtr = AllocResult.pMappedData;
    break;
  }
  case hipMemoryTypeManaged:
  case hipMemoryTypeUnified: {
    // Managed / unified: prefer HOST_VISIBLE | DEVICE_LOCAL (resizeable-BAR
    // or integrated-GPU shared memory). If the platform can't satisfy both,
    // VMA returns failure and we fall back to a pure host-visible mapping
    // (correctness preserved; device access just hits the slower path).
    AllocInfo.usage = VMA_MEMORY_USAGE_AUTO_PREFER_HOST;
    AllocInfo.requiredFlags = VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT;
    AllocInfo.preferredFlags = VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT |
                               VK_MEMORY_PROPERTY_HOST_COHERENT_BIT;
    AllocInfo.flags = VMA_ALLOCATION_CREATE_MAPPED_BIT |
                      VMA_ALLOCATION_CREATE_HOST_ACCESS_RANDOM_BIT;
    Status = vmaCreateBuffer(Allocator, &BufInfo, &AllocInfo, &Buffer,
                             &Allocation, &AllocResult);
    if (Status != VK_SUCCESS || Allocation == VK_NULL_HANDLE ||
        AllocResult.pMappedData == nullptr) {
      // Fallback: drop the DEVICE_LOCAL preference and retry as a pure
      // host-visible / host-coherent allocation. Slower for GPU access on
      // discrete GPUs without resizeable-BAR, but functionally correct.
      AllocInfo.usage = VMA_MEMORY_USAGE_CPU_TO_GPU;
      AllocInfo.requiredFlags = VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT |
                                VK_MEMORY_PROPERTY_HOST_COHERENT_BIT;
      AllocInfo.preferredFlags = 0;
      AllocInfo.flags = VMA_ALLOCATION_CREATE_MAPPED_BIT;
      Status = vmaCreateBuffer(Allocator, &BufInfo, &AllocInfo, &Buffer,
                               &Allocation, &AllocResult);
      if (Status != VK_SUCCESS || Allocation == VK_NULL_HANDLE ||
          AllocResult.pMappedData == nullptr)
        CHIPERR_LOG_AND_THROW("vmaCreateBuffer (managed) failed",
                              hipErrorOutOfMemory);
    }
    RetPtr = AllocResult.pMappedData;
    break;
  }
  default:
    CHIPERR_LOG_AND_THROW(
        "CHIPContextVulkan::allocateImpl: unsupported hipMemoryType",
        hipErrorInvalidValue);
  }

  DevPtrEntry Entry;
  Entry.Buffer = Buffer;
  Entry.Allocation = Allocation;
  Entry.AllocInfo = AllocResult;
  Entry.Size = Size;
  Entry.MemType = MemType;
  Entry.Flags = Flags;
  DevPtrToEntry_.emplace(static_cast<const void *>(RetPtr), Entry);
  return RetPtr;
}

bool CHIPContextVulkan::isAllocatedPtrMappedToVM(void *Ptr) {
  // For the Vulkan backend every pointer returned by allocateImpl is tracked
  // in DevPtrToEntry_: host / unified allocations are persistently mapped via
  // VMA, device-only allocations are synthetic cookies that the runtime never
  // dereferences on the host. Either way "is it ours?" reduces to "is it in
  // the table?".
  LOCK(ContextMtx); // CHIPContextVulkan::DevPtrToEntry_
  return DevPtrToEntry_.find(Ptr) != DevPtrToEntry_.end();
}

void CHIPContextVulkan::freeImpl(void *Ptr) {
  if (!Ptr)
    return;

  LOCK(ContextMtx); // CHIPContextVulkan::DevPtrToEntry_

  auto It = DevPtrToEntry_.find(Ptr);
  if (It == DevPtrToEntry_.end()) {
    // Mirror Level0 behavior: a free of an unknown pointer is logged and
    // ignored rather than throwing, so a stale free doesn't tear down the
    // whole process. The base AllocationTracker has already updated its
    // own bookkeeping by the time we get here.
    logError("CHIPContextVulkan::freeImpl: pointer {} not tracked by this "
             "context", Ptr);
    return;
  }

  CHIPDeviceVulkan *Dev = getVulkanDevice();
  VmaAllocator Allocator = Dev ? Dev->getAllocator() : VK_NULL_HANDLE;
  if (Allocator != VK_NULL_HANDLE)
    vmaDestroyBuffer(Allocator, It->second.Buffer, It->second.Allocation);
  // If the allocator is already gone (context torn down out-of-order), the
  // VkDevice teardown reclaims the VkDeviceMemory anyway. Drop the bookkeeping.
  DevPtrToEntry_.erase(It);
}

VkBuffer CHIPContextVulkan::translateDevPtrToBuffer(const void *DevPtr) const {
  auto It = DevPtrToEntry_.find(DevPtr);
  return It == DevPtrToEntry_.end() ? VK_NULL_HANDLE : It->second.Buffer;
}

const CHIPContextVulkan::DevPtrEntry *
CHIPContextVulkan::getDevPtrEntry(const void *DevPtr) const {
  auto It = DevPtrToEntry_.find(DevPtr);
  return It == DevPtrToEntry_.end() ? nullptr : &It->second;
}

const CHIPContextVulkan::DevPtrEntry *
CHIPContextVulkan::getDevPtrEntryContaining(const void *DevPtr,
                                            size_t &OutOffset) const {
  OutOffset = 0;
  if (!DevPtr)
    return nullptr;
  // Fast path: exact base.
  auto It = DevPtrToEntry_.find(DevPtr);
  if (It != DevPtrToEntry_.end()) {
    OutOffset = 0;
    return &It->second;
  }
  // Otherwise the entry with the greatest base below DevPtr, if it covers it.
  auto Ub = DevPtrToEntry_.upper_bound(DevPtr);
  if (Ub != DevPtrToEntry_.begin()) {
    --Ub;
    const auto *Bytes = static_cast<const uint8_t *>(DevPtr);
    const auto *BaseBytes = static_cast<const uint8_t *>(Ub->first);
    if (Bytes < BaseBytes + Ub->second.Size) {
      OutOffset = static_cast<size_t>(Bytes - BaseBytes);
      return &Ub->second;
    }
  }
  return nullptr;
}

void *CHIPContextVulkan::getNullArgPlaceholder() {
  std::call_once(NullArgOnce_, [this]() {
    NullArgPlaceholder_ = allocateImpl(256, 256, hipMemoryTypeDevice);
  });
  return NullArgPlaceholder_;
}

CHIPDeviceVulkan *CHIPContextVulkan::getVulkanDevice() const {
  return static_cast<CHIPDeviceVulkan *>(ChipDevice_);
}

