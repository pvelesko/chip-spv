CHIPDeviceVulkan::CHIPDeviceVulkan(CHIPContextVulkan *ChipContext,
                                   VkPhysicalDevice PhysDev, int Idx)
    : chipstar::Device(ChipContext, Idx), PhysicalDevice_(PhysDev) {}

CHIPDeviceVulkan::~CHIPDeviceVulkan() {
  // Tear down in reverse-creation order. Each handle is checked because the
  // ctor sequence may have bailed partway through (e.g. timestamp pool
  // creation skipped on devices without timestampValidBits).
  if (LogicalDevice_ != VK_NULL_HANDLE) {
    vkDeviceWaitIdle(LogicalDevice_);

    // Fence pool — drain before the device dies.
    {
      std::lock_guard<std::mutex> Lock(FencePoolMtx_);
      for (VkFence F : FencePool_)
        vkDestroyFence(LogicalDevice_, F, nullptr);
      FencePool_.clear();
    }
    if (TimestampQueryPool_ != VK_NULL_HANDLE) {
      vkDestroyQueryPool(LogicalDevice_, TimestampQueryPool_, nullptr);
      TimestampQueryPool_ = VK_NULL_HANDLE;
    }
    if (PipelineCache_ != VK_NULL_HANDLE) {
      vkDestroyPipelineCache(LogicalDevice_, PipelineCache_, nullptr);
      PipelineCache_ = VK_NULL_HANDLE;
    }
    if (CommandPool_ != VK_NULL_HANDLE) {
      vkDestroyCommandPool(LogicalDevice_, CommandPool_, nullptr);
      CommandPool_ = VK_NULL_HANDLE;
    }
    if (Allocator_ != VK_NULL_HANDLE) {
      vmaDestroyAllocator(Allocator_);
      Allocator_ = VK_NULL_HANDLE;
    }
    vkDestroyDevice(LogicalDevice_, nullptr);
    LogicalDevice_ = VK_NULL_HANDLE;
  }
}
CHIPDeviceVulkan *CHIPDeviceVulkan::create(CHIPContextVulkan *ChipContext,
                                           VkPhysicalDevice PhysDev, int Idx) {
  CHIPDeviceVulkan *Dev = new CHIPDeviceVulkan(ChipContext, PhysDev, Idx);
  // Ensure the context knows its device before Device::init() may call back
  // into the context (e.g. allocation paths from createQueue()).
  ChipContext->setDevice(Dev);

  // ----- Cache features / properties / subgroup info -----
  Dev->Properties_ = {};
  vkGetPhysicalDeviceProperties(PhysDev, &Dev->Properties_);
  Dev->Features_ = {};
  vkGetPhysicalDeviceFeatures(PhysDev, &Dev->Features_);
  Dev->SubgroupProperties_ = {};
  Dev->SubgroupProperties_.sType =
      VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_SUBGROUP_PROPERTIES;
  VkPhysicalDeviceProperties2 Props2{};
  Props2.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_PROPERTIES_2;
  Props2.pNext = &Dev->SubgroupProperties_;
  vkGetPhysicalDeviceProperties2(PhysDev, &Props2);

  // ----- Probe Vulkan 1.2 + Float16Int8 features -----
  VkPhysicalDeviceShaderFloat16Int8Features F16I8Features{};
  F16I8Features.sType =
      VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_SHADER_FLOAT16_INT8_FEATURES;
  VkPhysicalDeviceVulkan12Features V12Features{};
  V12Features.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_2_FEATURES;
  V12Features.pNext = &F16I8Features;
  VkPhysicalDeviceFeatures2 Feat2{};
  Feat2.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2;
  Feat2.pNext = &V12Features;
  vkGetPhysicalDeviceFeatures2(PhysDev, &Feat2);

  Dev->HasShaderInt8_ = (V12Features.shaderInt8 == VK_TRUE) ||
                        (F16I8Features.shaderInt8 == VK_TRUE);
  Dev->HasShaderInt64_ = Feat2.features.shaderInt64 == VK_TRUE;
  // Phase Z3: probe bufferDeviceAddress (Vulkan 1.2 core). Required for the
  // BDA path the bridging pass selects when a module has IGBAs (e.g.
  // pointer-inside-struct kernel args). Without it, push-constant BDA slots
  // would carry raw VmaAllocation cookies that OpConvertUToPtr can't resolve.
  Dev->HasBufferDeviceAddress_ = (V12Features.bufferDeviceAddress == VK_TRUE);

  // ----- Pick a compute-capable queue family -----
  uint32_t QFamCount = 0;
  vkGetPhysicalDeviceQueueFamilyProperties(PhysDev, &QFamCount, nullptr);
  std::vector<VkQueueFamilyProperties> QFamProps(QFamCount);
  vkGetPhysicalDeviceQueueFamilyProperties(PhysDev, &QFamCount,
                                           QFamProps.data());
  uint32_t QFamIdx = ~0u;
  // Prefer the universal (graphics+compute) family: on Mesa ANV the
  // compute-only family on Xe2 (Arc B570) leaves dispatch writes invisible
  // to the following transfer. Fall back to any COMPUTE family.
  for (uint32_t i = 0; i < QFamCount; ++i) {
    if ((QFamProps[i].queueFlags & VK_QUEUE_COMPUTE_BIT) &&
        (QFamProps[i].queueFlags & VK_QUEUE_GRAPHICS_BIT)) {
      QFamIdx = i;
      break;
    }
  }
  if (QFamIdx == ~0u) {
    for (uint32_t i = 0; i < QFamCount; ++i) {
      if (QFamProps[i].queueFlags & VK_QUEUE_COMPUTE_BIT) {
        QFamIdx = i;
        break;
      }
    }
  }
  if (QFamIdx == ~0u) {
    delete Dev;
    CHIPERR_LOG_AND_THROW(
        std::string("No compute-capable queue family on Vulkan device: ") +
            Dev->Properties_.deviceName,
        hipErrorInitializationError);
  }
  Dev->ComputeQueueFamilyIndex_ = QFamIdx;

  // ----- Validate VK_KHR_shader_non_semantic_info is exposed -----
  // Mandatory per Phase-1 worklog #10; we don't want to defer-detect this
  // and have I3 throw cryptically much later in the pipeline.
  uint32_t ExtCount = 0;
  vkEnumerateDeviceExtensionProperties(PhysDev, nullptr, &ExtCount, nullptr);
  std::vector<VkExtensionProperties> AvailExts(ExtCount);
  vkEnumerateDeviceExtensionProperties(PhysDev, nullptr, &ExtCount,
                                       AvailExts.data());
  if (!vkPropertyListContains(AvailExts, &VkExtensionProperties::extensionName,
                              VK_KHR_SHADER_NON_SEMANTIC_INFO_EXTENSION_NAME)) {
    delete Dev;
    CHIPERR_LOG_AND_THROW(
        std::string("Vulkan device lacks VK_KHR_shader_non_semantic_info: ") +
            Dev->Properties_.deviceName,
        hipErrorInitializationError);
  }

  // ----- Create the logical device -----
  const float QueuePriority = 1.0f;
  VkDeviceQueueCreateInfo QInfo{};
  QInfo.sType = VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO;
  QInfo.queueFamilyIndex = QFamIdx;
  QInfo.queueCount = 1;
  QInfo.pQueuePriorities = &QueuePriority;

  // Enable shaderInt8 + hostQueryReset + timelineSemaphore. The latter two
  // are 1.2 core but still require explicit feature opt-in. Other 1.2
  // capabilities (atomic_float, shader_clock, 16bit_storage) get gated
  // on per-module SPV inspection by I3 (out of scope for I1).
  VkPhysicalDeviceVulkan12Features Enable12{};
  Enable12.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_2_FEATURES;
  Enable12.shaderInt8 = Dev->HasShaderInt8_ ? VK_TRUE : VK_FALSE;
  Enable12.hostQueryReset = VK_TRUE;
  Enable12.timelineSemaphore = VK_TRUE;
  // Phase Z3: opt into bufferDeviceAddress when the device supports it. Used
  // by the BDA push-constant path for kernels emitted by the bridging pass'
  // rewriteKernelSignatureBDA. Capture-replay stays off — only needed for
  // validation-layer replay tooling, not runtime BDA lookup.
  Enable12.bufferDeviceAddress =
      Dev->HasBufferDeviceAddress_ ? VK_TRUE : VK_FALSE;
  Enable12.bufferDeviceAddressCaptureReplay = VK_FALSE;

  // Phase Z3: also opt into VK_KHR_maintenance4 (core in Vulkan 1.3). The
  // bridging pass + inject_reflection.py emit `OpExecutionModeId LocalSizeId`
  // with spec-constant workgroup dimensions — this requires the maintenance4
  // feature to be enabled. Without it, vkCreateShaderModule rejects every
  // kernel SPV with VUID-RuntimeSpirv-LocalSizeId-06434.
  VkPhysicalDeviceMaintenance4FeaturesKHR EnableM4{};
  EnableM4.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_MAINTENANCE_4_FEATURES_KHR;
  EnableM4.maintenance4 = VK_TRUE;

  VkPhysicalDeviceShaderAtomicInt64Features EnableAI64{};
  EnableAI64.sType =
      VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_SHADER_ATOMIC_INT64_FEATURES;
  EnableAI64.shaderBufferInt64Atomics =
      V12Features.shaderBufferInt64Atomics;
  EnableAI64.shaderSharedInt64Atomics =
      V12Features.shaderSharedInt64Atomics;
  EnableM4.pNext = &EnableAI64;

  Enable12.pNext = &EnableM4;

  VkPhysicalDeviceFeatures2 EnableFeat{};
  EnableFeat.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2;
  EnableFeat.pNext = &Enable12;
  EnableFeat.features.shaderInt64 = Dev->HasShaderInt64_ ? VK_TRUE : VK_FALSE;

  std::vector<const char *> DevExts = {
      VK_KHR_SHADER_NON_SEMANTIC_INFO_EXTENSION_NAME,
      VK_KHR_MAINTENANCE_4_EXTENSION_NAME,
  };

  VkDeviceCreateInfo DevInfo{};
  DevInfo.sType = VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO;
  DevInfo.pNext = &EnableFeat;
  DevInfo.queueCreateInfoCount = 1;
  DevInfo.pQueueCreateInfos = &QInfo;
  DevInfo.enabledExtensionCount = static_cast<uint32_t>(DevExts.size());
  DevInfo.ppEnabledExtensionNames = DevExts.data();

  VkResult R =
      vkCreateDevice(PhysDev, &DevInfo, nullptr, &Dev->LogicalDevice_);
  if (R != VK_SUCCESS) {
    delete Dev;
    CHIPERR_LOG_AND_THROW(std::string("vkCreateDevice failed: ") +
                              std::to_string(static_cast<int>(R)),
                          hipErrorInitializationError);
  }

  vkGetDeviceQueue(Dev->LogicalDevice_, QFamIdx, 0, &Dev->ComputeQueue_);

  // ----- VMA allocator -----
  // The instance handle lives on the Backend singleton; the singleton was
  // registered before initializeImpl() ran via setBackend().
  VmaAllocatorCreateInfo AInfo{};
  AInfo.physicalDevice = PhysDev;
  AInfo.device = Dev->LogicalDevice_;
  AInfo.instance = static_cast<CHIPBackendVulkan *>(::Backend)->getInstance();
  AInfo.vulkanApiVersion = VK_API_VERSION_1_2;
  // Phase Z3: enable BDA in VMA when the device supports it. The bridging
  // pass' BDA path (rewriteKernelSignatureBDA) emits PhysicalStorageBuffer64
  // SPIR-V with OpConvertUToPtr fed from push-constant ulong fields; those
  // ulongs are filled at dispatch time by vkGetBufferDeviceAddress on the
  // VkBuffer backing each HIP pointer kernel arg, which requires the buffer
  // to have been created with VK_BUFFER_USAGE_SHADER_DEVICE_ADDRESS_BIT —
  // VMA propagates that automatically only when this allocator flag is set.
  if (Dev->HasBufferDeviceAddress_)
    AInfo.flags |= VMA_ALLOCATOR_CREATE_BUFFER_DEVICE_ADDRESS_BIT;
  R = vmaCreateAllocator(&AInfo, &Dev->Allocator_);
  if (R != VK_SUCCESS) {
    vkDestroyDevice(Dev->LogicalDevice_, nullptr);
    delete Dev;
    CHIPERR_LOG_AND_THROW(std::string("vmaCreateAllocator failed: ") +
                              std::to_string(static_cast<int>(R)),
                          hipErrorInitializationError);
  }

  // ----- Command pool for transient one-shot buffers -----
  VkCommandPoolCreateInfo CPInfo{};
  CPInfo.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO;
  CPInfo.flags = VK_COMMAND_POOL_CREATE_TRANSIENT_BIT |
                 VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT;
  CPInfo.queueFamilyIndex = QFamIdx;
  R = vkCreateCommandPool(Dev->LogicalDevice_, &CPInfo, nullptr,
                          &Dev->CommandPool_);
  if (R != VK_SUCCESS) {
    vmaDestroyAllocator(Dev->Allocator_);
    vkDestroyDevice(Dev->LogicalDevice_, nullptr);
    delete Dev;
    CHIPERR_LOG_AND_THROW(std::string("vkCreateCommandPool failed: ") +
                              std::to_string(static_cast<int>(R)),
                          hipErrorInitializationError);
  }

  // ----- Pipeline cache (in-memory; persistence is a Phase-5 polish item) ---
  VkPipelineCacheCreateInfo PCInfo{};
  PCInfo.sType = VK_STRUCTURE_TYPE_PIPELINE_CACHE_CREATE_INFO;
  R = vkCreatePipelineCache(Dev->LogicalDevice_, &PCInfo, nullptr,
                            &Dev->PipelineCache_);
  if (R != VK_SUCCESS) {
    vkDestroyCommandPool(Dev->LogicalDevice_, Dev->CommandPool_, nullptr);
    vmaDestroyAllocator(Dev->Allocator_);
    vkDestroyDevice(Dev->LogicalDevice_, nullptr);
    delete Dev;
    CHIPERR_LOG_AND_THROW(std::string("vkCreatePipelineCache failed: ") +
                              std::to_string(static_cast<int>(R)),
                          hipErrorInitializationError);
  }

  // ----- Timestamp query pool -----
  if (Dev->Properties_.limits.timestampPeriod > 0.0f &&
      (Dev->Properties_.limits.timestampComputeAndGraphics ||
       QFamProps[QFamIdx].timestampValidBits > 0)) {
    VkQueryPoolCreateInfo QPInfo{};
    QPInfo.sType = VK_STRUCTURE_TYPE_QUERY_POOL_CREATE_INFO;
    QPInfo.queryType = VK_QUERY_TYPE_TIMESTAMP;
    QPInfo.queryCount = CHIPDeviceVulkan::TimestampPoolSize_;
    R = vkCreateQueryPool(Dev->LogicalDevice_, &QPInfo, nullptr,
                          &Dev->TimestampQueryPool_);
    if (R != VK_SUCCESS) {
      vkDestroyPipelineCache(Dev->LogicalDevice_, Dev->PipelineCache_, nullptr);
      vkDestroyCommandPool(Dev->LogicalDevice_, Dev->CommandPool_, nullptr);
      vmaDestroyAllocator(Dev->Allocator_);
      vkDestroyDevice(Dev->LogicalDevice_, nullptr);
      delete Dev;
      CHIPERR_LOG_AND_THROW(std::string("vkCreateQueryPool failed: ") +
                                std::to_string(static_cast<int>(R)),
                            hipErrorInitializationError);
    }
    // Seed the free list (push back so index 0 is the last pop).
    Dev->TimestampFreeList_.reserve(CHIPDeviceVulkan::TimestampPoolSize_);
    for (int32_t i =
             static_cast<int32_t>(CHIPDeviceVulkan::TimestampPoolSize_) - 1;
         i >= 0; --i) {
      Dev->TimestampFreeList_.push_back(i);
    }
    // Reset all slots up front. Requires the hostQueryReset 1.2 feature
    // (enabled above).
    vkResetQueryPool(Dev->LogicalDevice_, Dev->TimestampQueryPool_, 0,
                     CHIPDeviceVulkan::TimestampPoolSize_);
  } else {
    logWarn("Vulkan device '{}' does not support timestamp queries; HIP event "
            "timing will fall back to host clock.",
            Dev->Properties_.deviceName);
  }

  // chipstar::Device::init() populates HipDeviceProps_ and creates the legacy
  // default queue (calls back into createQueue, owned by I11).
  Dev->init();
  return Dev;
}

