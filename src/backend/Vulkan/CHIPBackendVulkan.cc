void CHIPDeviceVulkan::resetImpl() {
  // Spike-level reset: drain pending work and drop the in-memory pipeline
  // cache. Full destroy + recreate of the logical device is overkill for
  // the spike target (samples/2_vecadd) and risks tearing down state that
  // queues/contexts hold pointers to. A Phase-5 polish item.
  if (LogicalDevice_ != VK_NULL_HANDLE) {
    vkDeviceWaitIdle(LogicalDevice_);
    if (PipelineCache_ != VK_NULL_HANDLE) {
      vkDestroyPipelineCache(LogicalDevice_, PipelineCache_, nullptr);
      VkPipelineCacheCreateInfo PCInfo{};
      PCInfo.sType = VK_STRUCTURE_TYPE_PIPELINE_CACHE_CREATE_INFO;
      VkResult R = vkCreatePipelineCache(LogicalDevice_, &PCInfo, nullptr,
                                         &PipelineCache_);
      if (R != VK_SUCCESS) {
        PipelineCache_ = VK_NULL_HANDLE;
        logError("vkCreatePipelineCache failed in resetImpl: {}",
                 static_cast<int>(R));
      }
    }
  }
}

