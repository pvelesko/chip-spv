VkFence CHIPDeviceVulkan::acquireFence() {
  std::lock_guard<std::mutex> Lock(FencePoolMtx_);
  if (!FencePool_.empty()) {
    VkFence F = FencePool_.back();
    FencePool_.pop_back();
    // Caller is responsible for any prior reset; the pool only holds fences
    // that were reset-on-release. Defensive reset here keeps the API
    // hard-to-misuse.
    vkResetFences(LogicalDevice_, 1, &F);
    return F;
  }
  VkFenceCreateInfo FInfo{};
  FInfo.sType = VK_STRUCTURE_TYPE_FENCE_CREATE_INFO;
  // Created unsignaled by default — matches the post-acquire contract that
  // I5/I6 expect.
  VkFence F = VK_NULL_HANDLE;
  VkResult R = vkCreateFence(LogicalDevice_, &FInfo, nullptr, &F);
  if (R != VK_SUCCESS) {
    CHIPERR_LOG_AND_THROW(std::string("vkCreateFence failed: ") +
                              std::to_string(static_cast<int>(R)),
                          hipErrorOutOfMemory);
  }
  return F;
}

void CHIPDeviceVulkan::releaseFence(VkFence F) {
  if (F == VK_NULL_HANDLE)
    return;
  std::lock_guard<std::mutex> Lock(FencePoolMtx_);
  // Reset so the next acquirer gets a fence in the expected unsignaled state.
  vkResetFences(LogicalDevice_, 1, &F);
  FencePool_.push_back(F);
}

int32_t CHIPDeviceVulkan::acquireTimestampSlot() {
  if (TimestampQueryPool_ == VK_NULL_HANDLE)
    return -1;
  std::lock_guard<std::mutex> Lock(TimestampMtx_);
  if (TimestampFreeList_.empty())
    return -1;
  int32_t Slot = TimestampFreeList_.back();
  TimestampFreeList_.pop_back();
  // Reset just this slot so the next vkCmdWriteTimestamp into it starts from
  // a clean state. Requires the hostQueryReset 1.2 feature (enabled at
  // logical-device create time).
  vkResetQueryPool(LogicalDevice_, TimestampQueryPool_, static_cast<uint32_t>(Slot), 1);
  return Slot;
}

void CHIPDeviceVulkan::releaseTimestampSlot(int32_t Slot) {
  if (Slot < 0 || TimestampQueryPool_ == VK_NULL_HANDLE)
    return;
  std::lock_guard<std::mutex> Lock(TimestampMtx_);
  TimestampFreeList_.push_back(Slot);
}

// ============================================================================
// ===== I6: CHIPQueueVulkan (lifecycle + barriers)
// ===== I7: CHIPQueueVulkan::launchImpl
// ===== I8: CHIPQueueVulkan::memCopy*/memFill*
// ============================================================================

// ----------------------------------------------------------------------------
// Sync-primitive contract owned by I6:
//   - Each queue owns a per-queue
//     VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT command pool and a
//     fixed-size ring (RingCapacity_=16) of primary command buffers allocated
//     up front. acquireCmdBuffer() rotates the ring head and resets the
//     buffer; caller does vkBeginCommandBuffer/vkEndCommandBuffer.
//   - submitWithEvent() builds a VkSubmitInfo that signals BOTH the queue's
//     monotonic TimelineSemaphore_ (used by query()/finish() and as the
//     dependency anchor for in-queue ordering across submits) AND the
//     per-event binary VkFence (drives CHIPEventVulkan::wait /
//     updateFinishStatus in I5). Wait-deps in EventsToWaitFor are
//     host-resolved by waiting on their VkFences before submit; full GPU-side
//     dependency lowering with a timeline-wait pair is a Phase-5 polish item.
//   - finish() uses vkQueueWaitIdle (cheap on a single-queue device);
//     query() polls TimelineSemaphore_ via vkGetSemaphoreCounterValue.
//
// I7 (launchImpl) and I8 (memCopy*/memFill*) call acquireCmdBuffer() to get a
// recording-ready primary buffer, record their work, then call
// submitWithEvent(buf, eventsToWaitFor) to push the submit and get back the
// shared event already setRecording()'d.
// ----------------------------------------------------------------------------

CHIPQueueVulkan::CHIPQueueVulkan(chipstar::Device *ChipDevice,
                                 chipstar::QueueFlags Flags, int Priority)
    : chipstar::Queue(ChipDevice, Flags, Priority),
      ChipDevice_(static_cast<CHIPDeviceVulkan *>(ChipDevice)),
      CmdBufferRing_(RingCapacity_, VK_NULL_HANDLE) {
  VkDevice Dev = ChipDevice_->getLogicalDevice();
  if (Dev == VK_NULL_HANDLE) {
    // I1 owns logical-device bootstrap; constructing a queue before that
    // happened is a hard ordering bug. Throw with a named cause so the
    // first integration run pinpoints the missing step.
    CHIPERR_LOG_AND_THROW(
        "CHIPQueueVulkan ctor called before CHIPDeviceVulkan logical device "
        "was created",
        hipErrorTbd);
  }

  // ---- Per-queue command pool ----
  VkCommandPoolCreateInfo PoolCI{};
  PoolCI.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO;
  PoolCI.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT |
                 VK_COMMAND_POOL_CREATE_TRANSIENT_BIT;
  PoolCI.queueFamilyIndex = ChipDevice_->getComputeQueueFamilyIndex();
  checkVk(vkCreateCommandPool(Dev, &PoolCI, nullptr, &CommandPool_),
          "CHIPQueueVulkan: vkCreateCommandPool failed", hipErrorTbd);

  // ---- Pre-allocate the primary cmd-buffer ring ----
  VkCommandBufferAllocateInfo CBAI{};
  CBAI.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
  CBAI.commandPool = CommandPool_;
  CBAI.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
  CBAI.commandBufferCount = RingCapacity_;
  VkResult AllocR =
      vkAllocateCommandBuffers(Dev, &CBAI, CmdBufferRing_.data());
  if (AllocR != VK_SUCCESS) {
    vkDestroyCommandPool(Dev, CommandPool_, nullptr);
    CommandPool_ = VK_NULL_HANDLE;
    checkVk(AllocR, "CHIPQueueVulkan: vkAllocateCommandBuffers failed",
            hipErrorTbd);
  }

  // ---- Timeline semaphore for in-queue ordering across submits ----
  VkSemaphoreTypeCreateInfo SemTypeCI{};
  SemTypeCI.sType = VK_STRUCTURE_TYPE_SEMAPHORE_TYPE_CREATE_INFO;
  SemTypeCI.semaphoreType = VK_SEMAPHORE_TYPE_TIMELINE;
  SemTypeCI.initialValue = 0;
  VkSemaphoreCreateInfo SemCI{};
  SemCI.sType = VK_STRUCTURE_TYPE_SEMAPHORE_CREATE_INFO;
  SemCI.pNext = &SemTypeCI;
  VkResult SemR = vkCreateSemaphore(Dev, &SemCI, nullptr, &TimelineSemaphore_);
  if (SemR != VK_SUCCESS) {
    vkFreeCommandBuffers(Dev, CommandPool_, RingCapacity_,
                         CmdBufferRing_.data());
    vkDestroyCommandPool(Dev, CommandPool_, nullptr);
    CommandPool_ = VK_NULL_HANDLE;
    checkVk(SemR, "CHIPQueueVulkan: vkCreateSemaphore (timeline) failed",
            hipErrorTbd);
  }

  // ---- FinishFence_ used as the queue's generic submit-completion fence
  //      when an event-fence is not provided (e.g. enqueueMarkerImpl before
  //      I11/I5 are wired so Backend->createEventShared returns a real
  //      CHIPEventVulkan with a non-null VkFence).
  VkFenceCreateInfo FenceCI{};
  FenceCI.sType = VK_STRUCTURE_TYPE_FENCE_CREATE_INFO;
  // unsignaled — flags = 0
  VkResult FenceR = vkCreateFence(Dev, &FenceCI, nullptr, &FinishFence_);
  if (FenceR != VK_SUCCESS) {
    vkDestroySemaphore(Dev, TimelineSemaphore_, nullptr);
    TimelineSemaphore_ = VK_NULL_HANDLE;
    vkFreeCommandBuffers(Dev, CommandPool_, RingCapacity_,
                         CmdBufferRing_.data());
    vkDestroyCommandPool(Dev, CommandPool_, nullptr);
    CommandPool_ = VK_NULL_HANDLE;
    checkVk(FenceR, "CHIPQueueVulkan: vkCreateFence (FinishFence_) failed",
            hipErrorTbd);
  }

  // Queue priority is set on the VkDevice queue at I1's
  // VkDeviceQueueCreateInfo time. The Priority_ stored in the base class is
  // retained for HIP-side queries (getPriority()).
  (void)Priority;
}

CHIPQueueVulkan::~CHIPQueueVulkan() {
  // Z7: Teardown synchronization for detached threads.
  //
  // This dtor runs in two distinct contexts:
  //   1. Normal teardown on the main thread (Backend uninitialize destroys
  //      explicit user queues), with VkDevice still live.
  //   2. thread_local cleanup on detached worker threads exiting after main
  //      has already returned, in which case CHIPBackendVulkan::uninitialize
  //      may have already destroyed the VkDevice. Calling vkQueueWaitIdle /
  //      vkDestroyCommandPool against destroyed handles trips Vulkan
  //      validation and ultimately SIGABRTs the process at exit
  //      (Unit_TestThreadDetachCleanup).
  //
  // Serialize against CHIPBackendVulkan::uninitialize() via TeardownMtx_: if
  // we acquire the lock first the queue is fully torn down before the
  // backend can destroy its VkDevice; if uninitialize() acquired it first
  // ShuttingDown_ is true and we skip every Vulkan call. Either way the OS
  // reclaims the handles on process exit, so leaking them here is safe.
  std::lock_guard<std::recursive_mutex> TeardownLock(
      CHIPBackendVulkan::TeardownMtx_);

  VkDevice Dev =
      ChipDevice_ ? ChipDevice_->getLogicalDevice() : VK_NULL_HANDLE;
  if (Dev == VK_NULL_HANDLE)
    return;
  if (CHIPBackendVulkan::ShuttingDown_.load(std::memory_order_acquire)) {
    // VkDevice is about to be (or has already been) destroyed by the
    // backend's uninitialize(). Drop our handles without calling Vulkan.
    FinishFence_ = VK_NULL_HANDLE;
    TimelineSemaphore_ = VK_NULL_HANDLE;
    CommandPool_ = VK_NULL_HANDLE;
    return;
  }

  VkQueue Q = ChipDevice_->getComputeQueue();
  if (Q != VK_NULL_HANDLE) {
    // Drain any outstanding submits before tearing down resources they
    // reference. Ignore the return code; the device may already be lost.
    (void)vkQueueWaitIdle(Q);
  }

  // Release cross-queue dependency markers now that GPU work has drained.
  {
    std::lock_guard<std::mutex> Lock(CrossQueueDepsMtx_);
    CrossQueueDeps_.clear();
  }

  if (FinishFence_ != VK_NULL_HANDLE) {
    vkDestroyFence(Dev, FinishFence_, nullptr);
    FinishFence_ = VK_NULL_HANDLE;
  }
  if (TimelineSemaphore_ != VK_NULL_HANDLE) {
    vkDestroySemaphore(Dev, TimelineSemaphore_, nullptr);
    TimelineSemaphore_ = VK_NULL_HANDLE;
  }
  if (CommandPool_ != VK_NULL_HANDLE) {
    // vkDestroyCommandPool frees every buffer allocated from the pool.
    vkDestroyCommandPool(Dev, CommandPool_, nullptr);
    CommandPool_ = VK_NULL_HANDLE;
  }
}

void CHIPQueueVulkan::recordEvent(chipstar::Event *Event) {
  auto *EvVk = static_cast<CHIPEventVulkan *>(Event);
  if (EvVk == nullptr)
    CHIPERR_LOG_AND_THROW("CHIPQueueVulkan::recordEvent: null event",
                          hipErrorInvalidValue);
  auto CmdLock = lockCmdRecord();

  // Acquire a timestamp slot for this event. -1 means the device-level pool
  // is exhausted or not yet wired (I1/I5) — fall back to host-only timing.
  int32_t Slot = ChipDevice_->acquireTimestampSlot();
  EvVk->setTimestampSlot(Slot);

  // Always capture a host-side timestamp; getElapsedTime() in I5 uses this
  // when Slot==-1 or when the GPU query hasn't been pulled yet.
  EvVk->getHostTimestamp() = static_cast<uint64_t>(
      std::chrono::duration_cast<std::chrono::nanoseconds>(
          std::chrono::steady_clock::now().time_since_epoch())
          .count());

  VkCommandBuffer Cb = acquireCmdBuffer();
  VkCommandBufferBeginInfo BI{};
  BI.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
  BI.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
  checkVk(vkBeginCommandBuffer(Cb, &BI),
          "CHIPQueueVulkan::recordEvent: vkBeginCommandBuffer failed",
          hipErrorTbd);

  if (Slot >= 0 && ChipDevice_->getTimestampQueryPool() != VK_NULL_HANDLE) {
    // Per Vulkan spec, the slot must be reset before vkCmdWriteTimestamp.
    vkCmdResetQueryPool(Cb, ChipDevice_->getTimestampQueryPool(),
                        static_cast<uint32_t>(Slot), 1);
    vkCmdWriteTimestamp(Cb, VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT,
                        ChipDevice_->getTimestampQueryPool(),
                        static_cast<uint32_t>(Slot));
  }

  checkVk(vkEndCommandBuffer(Cb),
          "CHIPQueueVulkan::recordEvent: vkEndCommandBuffer failed",
          hipErrorTbd);

  // Submit using the timeline + the event's own VkFence as signal targets so
  // CHIPEventVulkan::wait() in I5 has a binary fence to host-wait on.
  uint64_t SignalTimelineVal;
  {
    std::lock_guard<std::mutex> Lock(QueueOpMtx_);
    SignalTimelineVal = ++TimelineValue_;
    noteRingSubmit(Cb, SignalTimelineVal);
  }

  VkTimelineSemaphoreSubmitInfo TsSubmit{};
  TsSubmit.sType = VK_STRUCTURE_TYPE_TIMELINE_SEMAPHORE_SUBMIT_INFO;
  TsSubmit.signalSemaphoreValueCount = 1;
  TsSubmit.pSignalSemaphoreValues = &SignalTimelineVal;

  VkSubmitInfo Submit{};
  Submit.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
  Submit.pNext = &TsSubmit;
  Submit.commandBufferCount = 1;
  Submit.pCommandBuffers = &Cb;
  Submit.signalSemaphoreCount = 1;
  Submit.pSignalSemaphores = &TimelineSemaphore_;

  VkFence SignalFence = EvVk->getFence();
  if (SignalFence == VK_NULL_HANDLE) {
    SignalFence = FinishFence_;
    (void)vkResetFences(ChipDevice_->getLogicalDevice(), 1, &SignalFence);
  }

  {
    // External sync required on VkQueue across all streams sharing this
    // device's compute queue.
    std::lock_guard<std::mutex> SubmitLock(ChipDevice_->getSubmitMtx());
    checkVk(vkQueueSubmit(ChipDevice_->getComputeQueue(), 1, &Submit,
                          SignalFence),
            "CHIPQueueVulkan::recordEvent: vkQueueSubmit failed", hipErrorTbd);
  }

  IsEmptyQueue_.store(false);
  EvVk->setRecording();
  // hipStreamWaitEvent waits on an event's dependencies; the marker signals
  // once everything submitted before the record has completed.
  CmdLock.unlock();
  Event->addDependency(enqueueMarkerImpl());
}

// ===== I8 helpers =====
//
// Staging-buffer lifetime for H2D/D2H transfers.
//
// The async memCopy path on the H2D side allocates a VMA-backed staging
// buffer, memcpys the host source into it, records a vkCmdCopyBuffer
// staging -> dst, submits via I6's submitWithEvent(), and returns the event.
// The staging buffer cannot be freed until the GPU has finished consuming
// it (i.e. the event's fence has signaled). The .hh forbids adding members
// to CHIPQueueVulkan from I8, so this file-scope registry owns the pending
// stagings and best-effort drains them on each entry to a memCopy/memFill
// call. The D2H path waits on the fence synchronously (the host needs the
// data immediately) and frees its staging buffer in place.
//
// Phase-5 polish (per the plan) introduces a real per-queue pool keyed on
// command-buffer ring slot; the simple list here is correct and matches
// the spike's "1 transfer per submit" usage shape.
namespace {

struct VulkanPendingStaging {
  VmaAllocator Allocator = VK_NULL_HANDLE;
  VkBuffer Buffer = VK_NULL_HANDLE;
  VmaAllocation Allocation = VK_NULL_HANDLE;
  // Holding a shared_ptr to the event keeps its VkFence alive long enough
  // for the drain step to query vkGetFenceStatus on it.
  std::shared_ptr<chipstar::Event> SignalEvent;
};

inline std::mutex &i8StagingMtx() {
  static std::mutex Mtx;
  return Mtx;
}

inline std::vector<VulkanPendingStaging> &i8PendingStagings() {
  static std::vector<VulkanPendingStaging> List;
  return List;
}

// Walk the pending-staging list and free any whose VkFence has signaled.
// Cheap to call; safe to invoke from any I8 entry point.
inline void i8DrainCompletedStagings(VkDevice Dev) {
  std::lock_guard<std::mutex> Lock(i8StagingMtx());
  auto &List = i8PendingStagings();
  auto It = List.begin();
  while (It != List.end()) {
    auto *Ev = static_cast<CHIPEventVulkan *>(It->SignalEvent.get());
    VkFence F = Ev ? Ev->getFence() : VK_NULL_HANDLE;
    // No fence or fence already signaled => safe to reclaim.
    bool Done = (F == VK_NULL_HANDLE) || Dev == VK_NULL_HANDLE ||
                vkGetFenceStatus(Dev, F) == VK_SUCCESS;
    if (Done) {
      if (It->Allocator != VK_NULL_HANDLE && It->Buffer != VK_NULL_HANDLE)
        vmaDestroyBuffer(It->Allocator, It->Buffer, It->Allocation);
      It = List.erase(It);
    } else {
      ++It;
    }
  }
}

// Track a staging buffer that is in-flight; pair this with an event whose
// fence signals when the GPU is done with the buffer.
inline void i8RecordPendingStaging(VmaAllocator Allocator, VkBuffer Buffer,
                                   VmaAllocation Allocation,
                                   std::shared_ptr<chipstar::Event> Event) {
  std::lock_guard<std::mutex> Lock(i8StagingMtx());
  i8PendingStagings().push_back(
      {Allocator, Buffer, Allocation, std::move(Event)});
}

// Allocate a host-visible / host-coherent staging buffer of `Size` bytes.
// `UsageFlags` is whichever of VK_BUFFER_USAGE_TRANSFER_{SRC,DST}_BIT the
// caller needs (the H2D path needs SRC, the D2H path needs DST).
// `MappedOut` returns the host-mapped pointer (VMA's MAPPED_BIT guarantees
// a persistent CPU mapping for the lifetime of the allocation).
inline bool i8AllocateStagingBuffer(VmaAllocator Allocator, size_t Size,
                                    VkBufferUsageFlags UsageFlags,
                                    VkBuffer &BufOut, VmaAllocation &AllocOut,
                                    void *&MappedOut) {
  VkBufferCreateInfo Info{};
  Info.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
  Info.size = Size;
  Info.usage = UsageFlags;
  Info.sharingMode = VK_SHARING_MODE_EXCLUSIVE;

  VmaAllocationCreateInfo AllocInfo{};
  AllocInfo.usage = VMA_MEMORY_USAGE_CPU_ONLY;
  AllocInfo.requiredFlags = VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT |
                            VK_MEMORY_PROPERTY_HOST_COHERENT_BIT;
  AllocInfo.flags = VMA_ALLOCATION_CREATE_MAPPED_BIT;

  VmaAllocationInfo Result{};
  VkResult Status = vmaCreateBuffer(Allocator, &Info, &AllocInfo, &BufOut,
                                    &AllocOut, &Result);
  if (Status != VK_SUCCESS || BufOut == VK_NULL_HANDLE ||
      Result.pMappedData == nullptr)
    return false;
  MappedOut = Result.pMappedData;
  return true;
}

// Tile `Pattern` (PatternSize bytes) into `Dst` (TotalSize bytes). Used by
// memFillAsyncImpl for non-4-byte pattern sizes (vkCmdFillBuffer only
// natively supports 4-byte patterns).
inline void i8TilePattern(void *Dst, size_t TotalSize, const void *Pattern,
                          size_t PatternSize) {
  auto *DstBytes = static_cast<uint8_t *>(Dst);
  const auto *PatBytes = static_cast<const uint8_t *>(Pattern);
  for (size_t i = 0; i < TotalSize; ++i)
    DstBytes[i] = PatBytes[i % PatternSize];
}

// Resolve a HIP pointer to its VkBuffer + byte offset (VK_NULL_HANDLE means
// the pointer is host-side / not registered). Accepts pointers into the
// middle of a hipMalloc'd region: getDevPtrEntryContaining() returns the
// owning entry and the offset of Ptr from the entry's base.
// `IsMappedAlloc` is set when the HIP pointer is itself a host-visible
// mapping (managed / host-visible-device-local) -- in that case the I8 path
// can short-circuit to a plain memcpy without a staging buffer.
// `OffsetOut` receives the byte offset within the returned VkBuffer (0 for
// the common case of callers passing the exact pointer from hipMalloc).
// `MappedBaseOut` is set to the host-visible base pointer when IsMappedAlloc
// is true (so callers can compute Ptr - MappedBase for in-place writes).
inline VkBuffer i8LookupVkBuffer(CHIPContextVulkan *Ctx, const void *Ptr,
                                 bool &IsMappedAlloc, VkDeviceSize &OffsetOut,
                                 const void *&MappedBaseOut) {
  IsMappedAlloc = false;
  OffsetOut = 0;
  MappedBaseOut = nullptr;
  if (!Ctx || !Ptr)
    return VK_NULL_HANDLE;
  size_t Offset = 0;
  const auto *Entry = Ctx->getDevPtrEntryContaining(Ptr, Offset);
  if (!Entry)
    return VK_NULL_HANDLE;
  OffsetOut = static_cast<VkDeviceSize>(Offset);
  if (Entry->AllocInfo.pMappedData) {
    // Pointer falls inside a host-visible mapped allocation.
    IsMappedAlloc = true;
    MappedBaseOut = Entry->AllocInfo.pMappedData;
  }
  return Entry->Buffer;
}

// Throw hipErrorInvalidValue when [Ptr, Ptr + Size) runs past the end of the
// registered allocation containing Ptr (unregistered host memory is fine).
inline void i8CheckFitsAllocation(CHIPContextVulkan *Ctx, const void *Ptr,
                                  size_t Size) {
  size_t Offset = 0;
  const auto *Entry = Ctx ? Ctx->getDevPtrEntryContaining(Ptr, Offset) : nullptr;
  if (Entry && Offset + Size > Entry->Size)
    CHIPERR_LOG_AND_THROW("Access exceeds the allocation", hipErrorInvalidValue);
}

// Backward-compatible 2-arg form for call sites that don't yet care about
// offsets (and that will continue to work for exact-base pointers).
inline VkBuffer i8LookupVkBuffer(CHIPContextVulkan *Ctx, const void *Ptr,
                                 bool &IsMappedAlloc) {
  VkDeviceSize IgnoredOffset = 0;
  const void *IgnoredBase = nullptr;
  return i8LookupVkBuffer(Ctx, Ptr, IsMappedAlloc, IgnoredOffset,
                          IgnoredBase);
}

// Begin recording on a primary command buffer obtained from the queue's
// ring (I6 owns acquireCmdBuffer). VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT
// matches the per-submit lifecycle the ring enforces.
inline VkCommandBuffer i8BeginCmdBuffer(CHIPQueueVulkan *Q) {
  VkCommandBuffer Cmd = Q->acquireCmdBuffer();
  VkCommandBufferBeginInfo BI{};
  BI.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
  BI.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
  VkResult R = vkBeginCommandBuffer(Cmd, &BI);
  if (R != VK_SUCCESS)
    CHIPERR_LOG_AND_THROW(
        std::string("vkBeginCommandBuffer failed VkResult=") +
            std::to_string(static_cast<int>(R)),
        hipErrorRuntimeMemory);
  return Cmd;
}

inline void i8EndCmdBuffer(VkCommandBuffer Cmd) {
  VkResult R = vkEndCommandBuffer(Cmd);
  if (R != VK_SUCCESS)
    CHIPERR_LOG_AND_THROW(
        std::string("vkEndCommandBuffer failed VkResult=") +
            std::to_string(static_cast<int>(R)),
        hipErrorRuntimeMemory);
}

} // namespace (I8 helpers)

// ----------------------------------------------------------------------------
// I8: memCopyAsyncImpl
// ----------------------------------------------------------------------------
//
// HIP memcpy with backend-specific direction handling:
//   * hipMemcpyDefault:    auto-detect direction from the pointer registry.
//   * hipMemcpyHostToHost: plain std::memcpy + a no-op event.
//   * hipMemcpyDeviceToDevice (both pointers are VkBuffers): vkCmdCopyBuffer
//     directly between the two device buffers.
//   * hipMemcpyHostToDevice (Src is host, Dst is VkBuffer): allocate a
//     staging buffer, memcpy host->staging, vkCmdCopyBuffer staging->Dst,
//     submit. The staging buffer is registered for deferred destruction
//     once the event's fence signals.
//   * hipMemcpyDeviceToHost (Src is VkBuffer, Dst is host): allocate a
//     staging buffer, vkCmdCopyBuffer Src->staging, submit, vkWaitForFences
//     on the event's fence, memcpy staging->host, destroy staging.
//     (Synchronous tail because the host needs the data immediately.)
//
// For "managed" / "host-visible device-local" allocs the HIP pointer is
// itself the host-mapped pointer; the transfer collapses to a plain
// std::memcpy without staging in both directions.
// ----------------------------------------------------------------------------
void CHIPQueueVulkan::waitSubmitted() {
  if (TimelineSemaphore_ == VK_NULL_HANDLE)
    return;
  uint64_t Target;
  {
    std::lock_guard<std::mutex> Lock(QueueOpMtx_);
    Target = TimelineValue_;
  }
  VkSemaphoreWaitInfo WI{};
  WI.sType = VK_STRUCTURE_TYPE_SEMAPHORE_WAIT_INFO;
  WI.semaphoreCount = 1;
  WI.pSemaphores = &TimelineSemaphore_;
  WI.pValues = &Target;
  checkVk(vkWaitSemaphores(ChipDevice_->getLogicalDevice(), &WI, UINT64_MAX),
          "CHIPQueueVulkan::waitSubmitted: vkWaitSemaphores failed",
          hipErrorTbd);
}

std::shared_ptr<chipstar::Event>
CHIPQueueVulkan::memCopyAsyncImpl(void *Dst, const void *Src, size_t Size,
                                  hipMemcpyKind Kind) {
  auto CmdLock = lockCmdRecord();
  CHIPContextVulkan *Ctx = getContext();
  CHIPDeviceVulkan *Dev = getVulkanDevice();
  VkDevice VkDev = Dev ? Dev->getLogicalDevice() : VK_NULL_HANDLE;
  VmaAllocator Allocator = Dev ? Dev->getAllocator() : VK_NULL_HANDLE;
  i8DrainCompletedStagings(VkDev);

  IsEmptyQueue_.store(false);

  // No-op fast path matching the HIP / OpenCL contract for Dst == Src.
  if (Dst == Src || Size == 0) {
    logTrace("CHIPQueueVulkan::memCopyAsync no-op (Dst==Src or Size==0)");
    {
      VkCommandBuffer EmptyCmd = i8BeginCmdBuffer(this);
      i8EndCmdBuffer(EmptyCmd);
      return submitWithEvent(EmptyCmd, {});
    }
  }

  // Resolve both endpoints; auto-detect Kind from the registry when Default.
  bool DstIsMapped = false, SrcIsMapped = false;
  VkDeviceSize DstOffset = 0, SrcOffset = 0;
  const void *DstMappedBase = nullptr;
  const void *SrcMappedBase = nullptr;
  VkBuffer DstBuf = i8LookupVkBuffer(Ctx, Dst, DstIsMapped, DstOffset,
                                     DstMappedBase);
  VkBuffer SrcBuf = i8LookupVkBuffer(Ctx, Src, SrcIsMapped, SrcOffset,
                                     SrcMappedBase);
  i8CheckFitsAllocation(Ctx, Dst, Size);
  i8CheckFitsAllocation(Ctx, Src, Size);

  if (Kind == hipMemcpyDefault) {
    if (DstBuf != VK_NULL_HANDLE && SrcBuf != VK_NULL_HANDLE)
      Kind = hipMemcpyDeviceToDevice;
    else if (DstBuf != VK_NULL_HANDLE)
      Kind = hipMemcpyHostToDevice;
    else if (SrcBuf != VK_NULL_HANDLE)
      Kind = hipMemcpyDeviceToHost;
    else
      Kind = hipMemcpyHostToHost;
  }

  // Host-only path AND mapped-alloc short-circuits: just memcpy and submit
  // an empty cmd buffer to get a properly-tracked event back.
  if (Kind == hipMemcpyHostToHost ||
      (Kind == hipMemcpyHostToDevice && DstIsMapped) ||
      (Kind == hipMemcpyDeviceToHost && SrcIsMapped) ||
      (Kind == hipMemcpyDeviceToDevice && DstIsMapped && SrcIsMapped)) {
    logTrace("CHIPQueueVulkan::memCopyAsync host-side memcpy {} -> {} / {} B",
             Src, Dst, Size);
    waitSubmitted();
    std::memcpy(Dst, Src, Size);
    {
      VkCommandBuffer EmptyCmd = i8BeginCmdBuffer(this);
      i8EndCmdBuffer(EmptyCmd);
      return submitWithEvent(EmptyCmd, {});
    }
  }

  // Validate endpoints for each non-host kind.
  switch (Kind) {
  case hipMemcpyDeviceToDevice:
    if (DstBuf == VK_NULL_HANDLE || SrcBuf == VK_NULL_HANDLE)
      CHIPERR_LOG_AND_THROW("memCopyAsync D2D: both pointers must be device",
                            hipErrorInvalidValue);
    break;
  case hipMemcpyHostToDevice:
    if (DstBuf == VK_NULL_HANDLE)
      CHIPERR_LOG_AND_THROW("memCopyAsync H2D: destination is not a device "
                            "pointer registered with this context",
                            hipErrorInvalidValue);
    break;
  case hipMemcpyDeviceToHost:
    if (SrcBuf == VK_NULL_HANDLE)
      CHIPERR_LOG_AND_THROW("memCopyAsync D2H: source is not a device "
                            "pointer registered with this context",
                            hipErrorInvalidValue);
    break;
  default:
    CHIPERR_LOG_AND_THROW("memCopyAsync: unsupported hipMemcpyKind",
                          hipErrorInvalidValue);
  }

  VkCommandBuffer Cmd = i8BeginCmdBuffer(this);

  // D2D: direct buffer-to-buffer copy, no staging involved.
  if (Kind == hipMemcpyDeviceToDevice) {
    VkBufferCopy Region{};
    Region.srcOffset = SrcOffset;
    Region.dstOffset = DstOffset;
    Region.size = Size;
    vkCmdCopyBuffer(Cmd, SrcBuf, DstBuf, 1, &Region);
    i8EndCmdBuffer(Cmd);
    auto Ev = submitWithEvent(Cmd, {});
    logTrace("CHIPQueueVulkan::memCopyAsync D2D {} -> {} / {} B", Src, Dst,
             Size);
    return Ev;
  }

  if (Allocator == VK_NULL_HANDLE)
    CHIPERR_LOG_AND_THROW("memCopyAsync: VMA allocator not initialized",
                          hipErrorRuntimeMemory);

  // H2D and D2H both need a staging buffer.
  VkBuffer Staging = VK_NULL_HANDLE;
  VmaAllocation StagingAlloc = VK_NULL_HANDLE;
  void *StagingMapped = nullptr;
  VkBufferUsageFlags UsageFlags = (Kind == hipMemcpyHostToDevice)
                                      ? VK_BUFFER_USAGE_TRANSFER_SRC_BIT
                                      : VK_BUFFER_USAGE_TRANSFER_DST_BIT;
  if (!i8AllocateStagingBuffer(Allocator, Size, UsageFlags, Staging,
                               StagingAlloc, StagingMapped))
    CHIPERR_LOG_AND_THROW(
        "memCopyAsync: failed to allocate host-visible staging buffer",
        hipErrorOutOfMemory);

  if (Kind == hipMemcpyHostToDevice) {
    // Stage on the host, then GPU copies staging -> Dst.
    std::memcpy(StagingMapped, Src, Size);
    VkBufferCopy Region{};
    Region.srcOffset = 0;
    Region.dstOffset = DstOffset;
    Region.size = Size;
    vkCmdCopyBuffer(Cmd, Staging, DstBuf, 1, &Region);
    i8EndCmdBuffer(Cmd);
    auto Ev = submitWithEvent(Cmd, {});
    // Defer staging-buffer destruction until the event's fence signals.
    i8RecordPendingStaging(Allocator, Staging, StagingAlloc, Ev);
    logTrace("CHIPQueueVulkan::memCopyAsync H2D {} -> {} / {} B (staged)", Src,
             Dst, Size);
    return Ev;
  }

  // hipMemcpyDeviceToHost: GPU copies Src -> staging, host waits, then
  // memcpys staging -> Dst. Synchronous tail by design (HIP semantics: the
  // host needs the data immediately on return).
  {
    VkBufferCopy Region{};
    Region.srcOffset = SrcOffset;
    Region.dstOffset = 0;
    Region.size = Size;
    vkCmdCopyBuffer(Cmd, SrcBuf, Staging, 1, &Region);
    i8EndCmdBuffer(Cmd);
    auto Ev = submitWithEvent(Cmd, {});

    auto *EvVk = static_cast<CHIPEventVulkan *>(Ev.get());
    VkFence F = EvVk ? EvVk->getFence() : VK_NULL_HANDLE;
    if (F != VK_NULL_HANDLE && VkDev != VK_NULL_HANDLE) {
      VkResult WaitRes = vkWaitForFences(VkDev, 1, &F, VK_TRUE, UINT64_MAX);
      if (WaitRes != VK_SUCCESS)
        CHIPERR_LOG_AND_THROW(
            std::string("memCopyAsync D2H: vkWaitForFences failed VkResult=") +
                std::to_string(static_cast<int>(WaitRes)),
            hipErrorRuntimeMemory);
    }
    std::memcpy(Dst, StagingMapped, Size);
    vmaDestroyBuffer(Allocator, Staging, StagingAlloc);
    logTrace("CHIPQueueVulkan::memCopyAsync D2H {} -> {} / {} B (staged)", Src,
             Dst, Size);
    return Ev;
  }
}

// ----------------------------------------------------------------------------
// I8: memFillAsyncImpl
// ----------------------------------------------------------------------------
//
// Patterned fill. Vulkan offers two relevant primitives:
//   * vkCmdFillBuffer accepts only a 4-byte pattern (and a 4-aligned size).
//   * vkCmdUpdateBuffer accepts up to 65536 bytes of inline data, but
//     copies at command-record time.
// Our strategy:
//   * PatternSize == 4 and Size 4-aligned: vkCmdFillBuffer (fast path).
//   * Other PatternSize: allocate a staging buffer with the pattern
//     pre-tiled, then vkCmdCopyBuffer staging -> Dst.
//   * If Dst is itself a host-mapped allocation, do the tile in place.
// ----------------------------------------------------------------------------
std::shared_ptr<chipstar::Event>
CHIPQueueVulkan::memFillAsyncImpl(void *Dst, size_t Size, const void *Pattern,
                                  size_t PatternSize) {
  auto CmdLock = lockCmdRecord();
  CHIPContextVulkan *Ctx = getContext();
  CHIPDeviceVulkan *Dev = getVulkanDevice();
  VkDevice VkDev = Dev ? Dev->getLogicalDevice() : VK_NULL_HANDLE;
  VmaAllocator Allocator = Dev ? Dev->getAllocator() : VK_NULL_HANDLE;
  i8DrainCompletedStagings(VkDev);

  IsEmptyQueue_.store(false);

  if (PatternSize == 0)
    CHIPERR_LOG_AND_THROW("memFillAsync: PatternSize must be > 0",
                          hipErrorInvalidValue);

  bool DstIsMapped = false;
  VkDeviceSize DstOffset = 0;
  const void *DstMappedBase = nullptr;
  VkBuffer DstBuf = i8LookupVkBuffer(Ctx, Dst, DstIsMapped, DstOffset,
                                     DstMappedBase);
  i8CheckFitsAllocation(Ctx, Dst, Size);

  // Host-side fallback for mapped/host-only pointers. Note: for mapped
  // device-side allocations the HIP pointer's virtual address IS the
  // host-visible mapping, so writing through `Dst` directly is correct
  // even when Dst is an offset within the alloc.
  if (DstBuf == VK_NULL_HANDLE || DstIsMapped) {
    waitSubmitted();
    logTrace("CHIPQueueVulkan::memFillAsync host-side fill {} / {} B (pat {})",
             Dst, Size, PatternSize);
    i8TilePattern(Dst, Size, Pattern, PatternSize);
    {
      VkCommandBuffer EmptyCmd = i8BeginCmdBuffer(this);
      i8EndCmdBuffer(EmptyCmd);
      return submitWithEvent(EmptyCmd, {});
    }
  }

  if (Size == 0)
    {
      VkCommandBuffer EmptyCmd = i8BeginCmdBuffer(this);
      i8EndCmdBuffer(EmptyCmd);
      return submitWithEvent(EmptyCmd, {});
    }

  VkCommandBuffer Cmd = i8BeginCmdBuffer(this);

  // Fast path: 4-byte pattern with a 4-aligned destination offset and
  // 4-aligned size goes straight through vkCmdFillBuffer. Spec note: the
  // dstOffset AND size args to vkCmdFillBuffer must each be a multiple of 4
  // (size may be VK_WHOLE_SIZE). When offset/size aren't 4-aligned we fall
  // through to the staging path which has no such restriction.
  if (PatternSize == 4 && (Size % 4) == 0 && (DstOffset % 4) == 0) {
    uint32_t Value = 0;
    std::memcpy(&Value, Pattern, sizeof(Value));
    vkCmdFillBuffer(Cmd, DstBuf, DstOffset, Size, Value);
    i8EndCmdBuffer(Cmd);
    auto Ev = submitWithEvent(Cmd, {});
    logTrace(
        "CHIPQueueVulkan::memFillAsync vkCmdFillBuffer {} / {} B (value=0x{:x})",
        Dst, Size, Value);
    return Ev;
  }

  // General path: stage the tiled pattern then vkCmdCopyBuffer.
  if (Allocator == VK_NULL_HANDLE)
    CHIPERR_LOG_AND_THROW("memFillAsync: VMA allocator not initialized",
                          hipErrorRuntimeMemory);

  VkBuffer Staging = VK_NULL_HANDLE;
  VmaAllocation StagingAlloc = VK_NULL_HANDLE;
  void *StagingMapped = nullptr;
  if (!i8AllocateStagingBuffer(Allocator, Size,
                               VK_BUFFER_USAGE_TRANSFER_SRC_BIT, Staging,
                               StagingAlloc, StagingMapped))
    CHIPERR_LOG_AND_THROW("memFillAsync: failed to allocate staging buffer",
                          hipErrorOutOfMemory);

  i8TilePattern(StagingMapped, Size, Pattern, PatternSize);
  VkBufferCopy Region{};
  Region.srcOffset = 0;
  Region.dstOffset = DstOffset;
  Region.size = Size;
  vkCmdCopyBuffer(Cmd, Staging, DstBuf, 1, &Region);
  i8EndCmdBuffer(Cmd);
  auto Ev = submitWithEvent(Cmd, {});
  i8RecordPendingStaging(Allocator, Staging, StagingAlloc, Ev);
  logTrace(
      "CHIPQueueVulkan::memFillAsync staged-tile {} / {} B (PatternSize={})",
      Dst, Size, PatternSize);
  return Ev;
}

// ----------------------------------------------------------------------------
// I8: memCopy2DAsyncImpl
// ----------------------------------------------------------------------------
//
// 2D pitched copy: `Height` rows of `Width` bytes each, with DPitch /
// SPitch stride between rows. Batches all rows into a single vkQueueSubmit
// with `Height` VkBufferCopy regions, eliminating the per-row submit
// cascade (which previously produced flaky results under load due to the
// large number of in-flight staging buffers / fence churn).
// ----------------------------------------------------------------------------
std::shared_ptr<chipstar::Event> CHIPQueueVulkan::memCopy2DAsyncImpl(
    void *Dst, size_t DPitch, const void *Src, size_t SPitch, size_t Width,
    size_t Height, hipMemcpyKind Kind) {
  auto CmdLock = lockCmdRecord();
  CHIPContextVulkan *Ctx = getContext();
  CHIPDeviceVulkan *Dev = getVulkanDevice();
  VkDevice VkDev = Dev ? Dev->getLogicalDevice() : VK_NULL_HANDLE;
  VmaAllocator Allocator = Dev ? Dev->getAllocator() : VK_NULL_HANDLE;
  i8DrainCompletedStagings(VkDev);

  // Empty-rectangle case: still return a tracked event so the runtime can
  // wait on / pass through the result.
  if (Height == 0 || Width == 0) {
    VkCommandBuffer EmptyCmd = i8BeginCmdBuffer(this);
    i8EndCmdBuffer(EmptyCmd);
    return submitWithEvent(EmptyCmd, {});
  }

  IsEmptyQueue_.store(false);

  // Resolve endpoints once (range-aware so offset pointers work).
  bool DstIsMapped = false, SrcIsMapped = false;
  VkDeviceSize DstOffset = 0, SrcOffset = 0;
  const void *DstMappedBase = nullptr;
  const void *SrcMappedBase = nullptr;
  VkBuffer DstBuf =
      i8LookupVkBuffer(Ctx, Dst, DstIsMapped, DstOffset, DstMappedBase);
  VkBuffer SrcBuf =
      i8LookupVkBuffer(Ctx, Src, SrcIsMapped, SrcOffset, SrcMappedBase);

  if (Kind == hipMemcpyDefault) {
    if (DstBuf != VK_NULL_HANDLE && SrcBuf != VK_NULL_HANDLE)
      Kind = hipMemcpyDeviceToDevice;
    else if (DstBuf != VK_NULL_HANDLE)
      Kind = hipMemcpyHostToDevice;
    else if (SrcBuf != VK_NULL_HANDLE)
      Kind = hipMemcpyDeviceToHost;
    else
      Kind = hipMemcpyHostToHost;
  }

  // Host-only & mapped-alloc short-circuits — do the row-by-row memcpy on
  // the host. Mapped HIP pointers ARE the host-visible VA so writes go
  // straight through.
  if (Kind == hipMemcpyHostToHost ||
      (Kind == hipMemcpyHostToDevice && DstIsMapped) ||
      (Kind == hipMemcpyDeviceToHost && SrcIsMapped) ||
      (Kind == hipMemcpyDeviceToDevice && DstIsMapped && SrcIsMapped)) {
    waitSubmitted();
    for (size_t Row = 0; Row < Height; ++Row) {
      void *DstRow = static_cast<uint8_t *>(Dst) + Row * DPitch;
      const void *SrcRow = static_cast<const uint8_t *>(Src) + Row * SPitch;
      std::memcpy(DstRow, SrcRow, Width);
    }
    VkCommandBuffer EmptyCmd = i8BeginCmdBuffer(this);
    i8EndCmdBuffer(EmptyCmd);
    return submitWithEvent(EmptyCmd, {});
  }

  // Build per-row region list once.
  std::vector<VkBufferCopy> Regions;
  Regions.reserve(Height);

  VkCommandBuffer Cmd = i8BeginCmdBuffer(this);

  if (Kind == hipMemcpyDeviceToDevice) {
    if (DstBuf == VK_NULL_HANDLE || SrcBuf == VK_NULL_HANDLE)
      CHIPERR_LOG_AND_THROW("memCopy2DAsync D2D: both pointers must be device",
                            hipErrorInvalidValue);
    for (size_t Row = 0; Row < Height; ++Row) {
      VkBufferCopy R{};
      R.srcOffset = SrcOffset + Row * SPitch;
      R.dstOffset = DstOffset + Row * DPitch;
      R.size = Width;
      Regions.push_back(R);
    }
    vkCmdCopyBuffer(Cmd, SrcBuf, DstBuf, static_cast<uint32_t>(Regions.size()),
                    Regions.data());
    i8EndCmdBuffer(Cmd);
    return submitWithEvent(Cmd, {});
  }

  // H2D / D2H: single staging buffer for the entire rectangle, packed
  // contiguously (Width*Height bytes), then copied to/from the device
  // buffer at the per-row pitched offsets.
  if (Allocator == VK_NULL_HANDLE)
    CHIPERR_LOG_AND_THROW("memCopy2DAsync: VMA allocator not initialized",
                          hipErrorRuntimeMemory);

  const size_t StagingSize = Width * Height;
  VkBuffer Staging = VK_NULL_HANDLE;
  VmaAllocation StagingAlloc = VK_NULL_HANDLE;
  void *StagingMapped = nullptr;
  VkBufferUsageFlags UsageFlags = (Kind == hipMemcpyHostToDevice)
                                      ? VK_BUFFER_USAGE_TRANSFER_SRC_BIT
                                      : VK_BUFFER_USAGE_TRANSFER_DST_BIT;
  if (!i8AllocateStagingBuffer(Allocator, StagingSize, UsageFlags, Staging,
                               StagingAlloc, StagingMapped))
    CHIPERR_LOG_AND_THROW(
        "memCopy2DAsync: failed to allocate host-visible staging buffer",
        hipErrorOutOfMemory);

  if (Kind == hipMemcpyHostToDevice) {
    if (DstBuf == VK_NULL_HANDLE)
      CHIPERR_LOG_AND_THROW("memCopy2DAsync H2D: destination is not a device "
                            "pointer registered with this context",
                            hipErrorInvalidValue);
    // Pack host rows into the staging buffer.
    for (size_t Row = 0; Row < Height; ++Row) {
      const void *SrcRow = static_cast<const uint8_t *>(Src) + Row * SPitch;
      std::memcpy(static_cast<uint8_t *>(StagingMapped) + Row * Width, SrcRow,
                  Width);
      VkBufferCopy R{};
      R.srcOffset = Row * Width;
      R.dstOffset = DstOffset + Row * DPitch;
      R.size = Width;
      Regions.push_back(R);
    }
    vkCmdCopyBuffer(Cmd, Staging, DstBuf, static_cast<uint32_t>(Regions.size()),
                    Regions.data());
    i8EndCmdBuffer(Cmd);
    auto Ev = submitWithEvent(Cmd, {});
    i8RecordPendingStaging(Allocator, Staging, StagingAlloc, Ev);
    return Ev;
  }

  // D2H: single contiguous staging buffer, vkCmdCopyBuffer per-row, host wait,
  // then memcpy staging -> host with per-row pitches.
  if (SrcBuf == VK_NULL_HANDLE)
    CHIPERR_LOG_AND_THROW("memCopy2DAsync D2H: source is not a device pointer "
                          "registered with this context",
                          hipErrorInvalidValue);
  for (size_t Row = 0; Row < Height; ++Row) {
    VkBufferCopy R{};
    R.srcOffset = SrcOffset + Row * SPitch;
    R.dstOffset = Row * Width;
    R.size = Width;
    Regions.push_back(R);
  }
  vkCmdCopyBuffer(Cmd, SrcBuf, Staging, static_cast<uint32_t>(Regions.size()),
                  Regions.data());
  i8EndCmdBuffer(Cmd);
  auto Ev = submitWithEvent(Cmd, {});

  auto *EvVk = static_cast<CHIPEventVulkan *>(Ev.get());
  VkFence F = EvVk ? EvVk->getFence() : VK_NULL_HANDLE;
  if (F != VK_NULL_HANDLE && VkDev != VK_NULL_HANDLE) {
    VkResult WaitRes = vkWaitForFences(VkDev, 1, &F, VK_TRUE, UINT64_MAX);
    if (WaitRes != VK_SUCCESS)
      CHIPERR_LOG_AND_THROW(
          std::string("memCopy2DAsync D2H: vkWaitForFences failed VkResult=") +
              std::to_string(static_cast<int>(WaitRes)),
          hipErrorRuntimeMemory);
  }
  // Unpack staging into the host destination with per-row destination pitch.
  for (size_t Row = 0; Row < Height; ++Row) {
    void *DstRow = static_cast<uint8_t *>(Dst) + Row * DPitch;
    std::memcpy(DstRow,
                static_cast<const uint8_t *>(StagingMapped) + Row * Width,
                Width);
  }
  vmaDestroyBuffer(Allocator, Staging, StagingAlloc);
  return Ev;
}

// ----------------------------------------------------------------------------
// I8: memCopy3DAsyncImpl
// ----------------------------------------------------------------------------
//
// 3D pitched copy. Depth slices of Height rows of Width bytes each:
//   slice stride = DSPitch (Dst) / SSPitch (Src)
//   row stride   = DPitch  (Dst) / SPitch  (Src)
// Batches all Depth*Height rows into a single vkQueueSubmit, mirroring the
// 2D path.
// ----------------------------------------------------------------------------
std::shared_ptr<chipstar::Event> CHIPQueueVulkan::memCopy3DAsyncImpl(
    void *Dst, size_t DPitch, size_t DSPitch, const void *Src, size_t SPitch,
    size_t SSPitch, size_t Width, size_t Height, size_t Depth,
    hipMemcpyKind Kind) {
  auto CmdLock = lockCmdRecord();
  CHIPContextVulkan *Ctx = getContext();
  CHIPDeviceVulkan *Dev = getVulkanDevice();
  VkDevice VkDev = Dev ? Dev->getLogicalDevice() : VK_NULL_HANDLE;
  VmaAllocator Allocator = Dev ? Dev->getAllocator() : VK_NULL_HANDLE;
  i8DrainCompletedStagings(VkDev);

  if (Depth == 0 || Height == 0 || Width == 0) {
    VkCommandBuffer EmptyCmd = i8BeginCmdBuffer(this);
    i8EndCmdBuffer(EmptyCmd);
    return submitWithEvent(EmptyCmd, {});
  }
  IsEmptyQueue_.store(false);

  bool DstIsMapped = false, SrcIsMapped = false;
  VkDeviceSize DstOffset = 0, SrcOffset = 0;
  const void *DstMappedBase = nullptr;
  const void *SrcMappedBase = nullptr;
  VkBuffer DstBuf =
      i8LookupVkBuffer(Ctx, Dst, DstIsMapped, DstOffset, DstMappedBase);
  VkBuffer SrcBuf =
      i8LookupVkBuffer(Ctx, Src, SrcIsMapped, SrcOffset, SrcMappedBase);

  if (Kind == hipMemcpyDefault) {
    if (DstBuf != VK_NULL_HANDLE && SrcBuf != VK_NULL_HANDLE)
      Kind = hipMemcpyDeviceToDevice;
    else if (DstBuf != VK_NULL_HANDLE)
      Kind = hipMemcpyHostToDevice;
    else if (SrcBuf != VK_NULL_HANDLE)
      Kind = hipMemcpyDeviceToHost;
    else
      Kind = hipMemcpyHostToHost;
  }

  if (Kind == hipMemcpyHostToHost ||
      (Kind == hipMemcpyHostToDevice && DstIsMapped) ||
      (Kind == hipMemcpyDeviceToHost && SrcIsMapped) ||
      (Kind == hipMemcpyDeviceToDevice && DstIsMapped && SrcIsMapped)) {
    waitSubmitted();
    for (size_t S = 0; S < Depth; ++S)
      for (size_t R = 0; R < Height; ++R) {
        void *DstRow =
            static_cast<uint8_t *>(Dst) + S * DSPitch + R * DPitch;
        const void *SrcRow =
            static_cast<const uint8_t *>(Src) + S * SSPitch + R * SPitch;
        std::memcpy(DstRow, SrcRow, Width);
      }
    VkCommandBuffer EmptyCmd = i8BeginCmdBuffer(this);
    i8EndCmdBuffer(EmptyCmd);
    return submitWithEvent(EmptyCmd, {});
  }

  const size_t NumRows = Depth * Height;
  std::vector<VkBufferCopy> Regions;
  Regions.reserve(NumRows);
  VkCommandBuffer Cmd = i8BeginCmdBuffer(this);

  if (Kind == hipMemcpyDeviceToDevice) {
    if (DstBuf == VK_NULL_HANDLE || SrcBuf == VK_NULL_HANDLE)
      CHIPERR_LOG_AND_THROW("memCopy3DAsync D2D: both pointers must be device",
                            hipErrorInvalidValue);
    for (size_t S = 0; S < Depth; ++S)
      for (size_t R = 0; R < Height; ++R) {
        VkBufferCopy Reg{};
        Reg.srcOffset = SrcOffset + S * SSPitch + R * SPitch;
        Reg.dstOffset = DstOffset + S * DSPitch + R * DPitch;
        Reg.size = Width;
        Regions.push_back(Reg);
      }
    vkCmdCopyBuffer(Cmd, SrcBuf, DstBuf, static_cast<uint32_t>(Regions.size()),
                    Regions.data());
    i8EndCmdBuffer(Cmd);
    return submitWithEvent(Cmd, {});
  }

  if (Allocator == VK_NULL_HANDLE)
    CHIPERR_LOG_AND_THROW("memCopy3DAsync: VMA allocator not initialized",
                          hipErrorRuntimeMemory);

  const size_t StagingSize = Width * NumRows;
  VkBuffer Staging = VK_NULL_HANDLE;
  VmaAllocation StagingAlloc = VK_NULL_HANDLE;
  void *StagingMapped = nullptr;
  VkBufferUsageFlags UsageFlags = (Kind == hipMemcpyHostToDevice)
                                      ? VK_BUFFER_USAGE_TRANSFER_SRC_BIT
                                      : VK_BUFFER_USAGE_TRANSFER_DST_BIT;
  if (!i8AllocateStagingBuffer(Allocator, StagingSize, UsageFlags, Staging,
                               StagingAlloc, StagingMapped))
    CHIPERR_LOG_AND_THROW(
        "memCopy3DAsync: failed to allocate host-visible staging buffer",
        hipErrorOutOfMemory);

  if (Kind == hipMemcpyHostToDevice) {
    if (DstBuf == VK_NULL_HANDLE)
      CHIPERR_LOG_AND_THROW("memCopy3DAsync H2D: destination is not a device "
                            "pointer registered with this context",
                            hipErrorInvalidValue);
    size_t Idx = 0;
    for (size_t S = 0; S < Depth; ++S)
      for (size_t R = 0; R < Height; ++R, ++Idx) {
        const void *SrcRow =
            static_cast<const uint8_t *>(Src) + S * SSPitch + R * SPitch;
        std::memcpy(static_cast<uint8_t *>(StagingMapped) + Idx * Width, SrcRow,
                    Width);
        VkBufferCopy Reg{};
        Reg.srcOffset = Idx * Width;
        Reg.dstOffset = DstOffset + S * DSPitch + R * DPitch;
        Reg.size = Width;
        Regions.push_back(Reg);
      }
    vkCmdCopyBuffer(Cmd, Staging, DstBuf, static_cast<uint32_t>(Regions.size()),
                    Regions.data());
    i8EndCmdBuffer(Cmd);
    auto Ev = submitWithEvent(Cmd, {});
    i8RecordPendingStaging(Allocator, Staging, StagingAlloc, Ev);
    return Ev;
  }

  // D2H
  if (SrcBuf == VK_NULL_HANDLE)
    CHIPERR_LOG_AND_THROW("memCopy3DAsync D2H: source is not a device pointer "
                          "registered with this context",
                          hipErrorInvalidValue);
  size_t Idx = 0;
  for (size_t S = 0; S < Depth; ++S)
    for (size_t R = 0; R < Height; ++R, ++Idx) {
      VkBufferCopy Reg{};
      Reg.srcOffset = SrcOffset + S * SSPitch + R * SPitch;
      Reg.dstOffset = Idx * Width;
      Reg.size = Width;
      Regions.push_back(Reg);
    }
  vkCmdCopyBuffer(Cmd, SrcBuf, Staging, static_cast<uint32_t>(Regions.size()),
                  Regions.data());
  i8EndCmdBuffer(Cmd);
  auto Ev = submitWithEvent(Cmd, {});
  auto *EvVk = static_cast<CHIPEventVulkan *>(Ev.get());
  VkFence F = EvVk ? EvVk->getFence() : VK_NULL_HANDLE;
  if (F != VK_NULL_HANDLE && VkDev != VK_NULL_HANDLE) {
    VkResult WaitRes = vkWaitForFences(VkDev, 1, &F, VK_TRUE, UINT64_MAX);
    if (WaitRes != VK_SUCCESS)
      CHIPERR_LOG_AND_THROW(
          std::string("memCopy3DAsync D2H: vkWaitForFences failed VkResult=") +
              std::to_string(static_cast<int>(WaitRes)),
          hipErrorRuntimeMemory);
  }
  Idx = 0;
  for (size_t S = 0; S < Depth; ++S)
    for (size_t R = 0; R < Height; ++R, ++Idx) {
      void *DstRow = static_cast<uint8_t *>(Dst) + S * DSPitch + R * DPitch;
      std::memcpy(DstRow,
                  static_cast<const uint8_t *>(StagingMapped) + Idx * Width,
                  Width);
    }
  vmaDestroyBuffer(Allocator, Staging, StagingAlloc);
  return Ev;
}

// ----------------------------------------------------------------------------
// I8: memFillAsync2D (override)
// ----------------------------------------------------------------------------
//
// 2D pitched fill: `Height` rows of `Width` bytes each at stride `Pitch`,
// using the byte `Value`. The base implementation issues `Height` separate
// memFillAsyncImpl calls which under heavy load (e.g. Width=Height=256)
// triggers a per-row submit cascade plus per-row staging allocations.
//
// Vulkan-side strategy:
//   * vkCmdFillBuffer only supports 4-byte patterns, and the test value is
//     a single byte. We broadcast the byte into a 4-byte word
//     `vvvvvvvv` and use vkCmdFillBuffer when both Width and Pitch are
//     4-aligned (so each row's destination offset and size satisfy the
//     spec). Each row is one fill command on the same cmd buffer.
//   * Otherwise stage one Width-byte tiled-pattern buffer and issue
//     `Height` vkCmdCopyBuffer regions against it -- single submit.
// ----------------------------------------------------------------------------
void CHIPQueueVulkan::memFillAsync2D(void *Dst, size_t Pitch, int Value,
                                     size_t Width, size_t Height) {
  if (Width == 0 || Height == 0)
    return;

  auto CmdLock = lockCmdRecord();
  CHIPContextVulkan *Ctx = getContext();
  CHIPDeviceVulkan *Dev = getVulkanDevice();
  VkDevice VkDev = Dev ? Dev->getLogicalDevice() : VK_NULL_HANDLE;
  VmaAllocator Allocator = Dev ? Dev->getAllocator() : VK_NULL_HANDLE;
  i8DrainCompletedStagings(VkDev);
  IsEmptyQueue_.store(false);

  bool DstIsMapped = false;
  VkDeviceSize DstOffset = 0;
  const void *DstMappedBase = nullptr;
  VkBuffer DstBuf = i8LookupVkBuffer(Ctx, Dst, DstIsMapped, DstOffset,
                                     DstMappedBase);

  // Host-side fill (mapped or unregistered host pointer).
  if (DstBuf == VK_NULL_HANDLE || DstIsMapped) {
    waitSubmitted();
    unsigned char Byte = static_cast<unsigned char>(Value);
    for (size_t R = 0; R < Height; ++R) {
      void *Row = static_cast<uint8_t *>(Dst) + R * Pitch;
      std::memset(Row, Byte, Width);
    }
    VkCommandBuffer EmptyCmd = i8BeginCmdBuffer(this);
    i8EndCmdBuffer(EmptyCmd);
    auto Ev = submitWithEvent(EmptyCmd, {});
    Ev->Msg = "memFillAsync2D";
    return;
  }

  VkCommandBuffer Cmd = i8BeginCmdBuffer(this);

  // Fast path: broadcast byte into uint32 and fire vkCmdFillBuffer per row
  // when Width and per-row dst offsets are 4-aligned. The dst offset is
  // DstOffset + R*Pitch; the alignment of all of these depends on
  // DstOffset%4, Pitch%4, Width%4 all being 0.
  if ((Width % 4) == 0 && (Pitch % 4) == 0 && (DstOffset % 4) == 0) {
    unsigned char Byte = static_cast<unsigned char>(Value);
    uint32_t Word = static_cast<uint32_t>(Byte);
    Word |= Word << 8;
    Word |= Word << 16;
    for (size_t R = 0; R < Height; ++R)
      vkCmdFillBuffer(Cmd, DstBuf, DstOffset + R * Pitch, Width, Word);
    i8EndCmdBuffer(Cmd);
    auto Ev = submitWithEvent(Cmd, {});
    Ev->Msg = "memFillAsync2D";
    return;
  }

  // General path: one Width-byte staging buffer with the tiled pattern,
  // copied into each row with `Height` VkBufferCopy regions.
  if (Allocator == VK_NULL_HANDLE)
    CHIPERR_LOG_AND_THROW("memFillAsync2D: VMA allocator not initialized",
                          hipErrorRuntimeMemory);

  VkBuffer Staging = VK_NULL_HANDLE;
  VmaAllocation StagingAlloc = VK_NULL_HANDLE;
  void *StagingMapped = nullptr;
  if (!i8AllocateStagingBuffer(Allocator, Width,
                               VK_BUFFER_USAGE_TRANSFER_SRC_BIT, Staging,
                               StagingAlloc, StagingMapped))
    CHIPERR_LOG_AND_THROW("memFillAsync2D: failed to allocate staging buffer",
                          hipErrorOutOfMemory);
  unsigned char Byte = static_cast<unsigned char>(Value);
  std::memset(StagingMapped, Byte, Width);

  std::vector<VkBufferCopy> Regions;
  Regions.reserve(Height);
  for (size_t R = 0; R < Height; ++R) {
    VkBufferCopy Reg{};
    Reg.srcOffset = 0;
    Reg.dstOffset = DstOffset + R * Pitch;
    Reg.size = Width;
    Regions.push_back(Reg);
  }
  vkCmdCopyBuffer(Cmd, Staging, DstBuf, static_cast<uint32_t>(Regions.size()),
                  Regions.data());
  i8EndCmdBuffer(Cmd);
  auto Ev = submitWithEvent(Cmd, {});
  i8RecordPendingStaging(Allocator, Staging, StagingAlloc, Ev);
  Ev->Msg = "memFillAsync2D";
}

// ----------------------------------------------------------------------------
// I8: memFillAsync3D (override)
// ----------------------------------------------------------------------------
//
// 3D pitched fill. PitchedDevPtr provides the base, row pitch, and slice
// y-stride. Same strategy as memFillAsync2D, batched across Depth*Height
// rows.
// ----------------------------------------------------------------------------
void CHIPQueueVulkan::memFillAsync3D(hipPitchedPtr PitchedDevPtr, int Value,
                                     hipExtent Extent) {
  const size_t Width = Extent.width;
  const size_t Height = Extent.height;
  const size_t Depth = Extent.depth;
  if (Width == 0 || Height == 0 || Depth == 0)
    return;

  auto CmdLock = lockCmdRecord();

  void *Dst = PitchedDevPtr.ptr;
  const size_t Pitch = PitchedDevPtr.pitch;
  const size_t SlicePitch = Pitch * PitchedDevPtr.ysize;

  CHIPContextVulkan *Ctx = getContext();
  CHIPDeviceVulkan *Dev = getVulkanDevice();
  VkDevice VkDev = Dev ? Dev->getLogicalDevice() : VK_NULL_HANDLE;
  VmaAllocator Allocator = Dev ? Dev->getAllocator() : VK_NULL_HANDLE;
  i8DrainCompletedStagings(VkDev);
  IsEmptyQueue_.store(false);

  bool DstIsMapped = false;
  VkDeviceSize DstOffset = 0;
  const void *DstMappedBase = nullptr;
  VkBuffer DstBuf = i8LookupVkBuffer(Ctx, Dst, DstIsMapped, DstOffset,
                                     DstMappedBase);

  if (DstBuf == VK_NULL_HANDLE || DstIsMapped) {
    waitSubmitted();
    unsigned char Byte = static_cast<unsigned char>(Value);
    for (size_t S = 0; S < Depth; ++S)
      for (size_t R = 0; R < Height; ++R) {
        void *Row = static_cast<uint8_t *>(Dst) + S * SlicePitch + R * Pitch;
        std::memset(Row, Byte, Width);
      }
    VkCommandBuffer EmptyCmd = i8BeginCmdBuffer(this);
    i8EndCmdBuffer(EmptyCmd);
    auto Ev = submitWithEvent(EmptyCmd, {});
    Ev->Msg = "memFillAsync3D";
    return;
  }

  VkCommandBuffer Cmd = i8BeginCmdBuffer(this);

  if ((Width % 4) == 0 && (Pitch % 4) == 0 && (DstOffset % 4) == 0 &&
      (SlicePitch % 4) == 0) {
    unsigned char Byte = static_cast<unsigned char>(Value);
    uint32_t Word = static_cast<uint32_t>(Byte);
    Word |= Word << 8;
    Word |= Word << 16;
    // If consecutive rows in a slice are contiguous (Pitch == Width), fold
    // into a single per-slice fill. Similarly if SlicePitch == Pitch*Height
    // the whole volume is contiguous and we can issue one giant fill.
    const bool RowsContig = (Pitch == Width);
    const bool SlicesContig = RowsContig && (SlicePitch == Height * Pitch);
    if (SlicesContig) {
      vkCmdFillBuffer(Cmd, DstBuf, DstOffset, Width * Height * Depth, Word);
    } else if (RowsContig) {
      for (size_t S = 0; S < Depth; ++S)
        vkCmdFillBuffer(Cmd, DstBuf, DstOffset + S * SlicePitch,
                        Width * Height, Word);
    } else {
      for (size_t S = 0; S < Depth; ++S)
        for (size_t R = 0; R < Height; ++R)
          vkCmdFillBuffer(Cmd, DstBuf,
                          DstOffset + S * SlicePitch + R * Pitch, Width, Word);
    }
    i8EndCmdBuffer(Cmd);
    auto Ev = submitWithEvent(Cmd, {});
    Ev->Msg = "memFillAsync3D";
    return;
  }

  if (Allocator == VK_NULL_HANDLE)
    CHIPERR_LOG_AND_THROW("memFillAsync3D: VMA allocator not initialized",
                          hipErrorRuntimeMemory);

  VkBuffer Staging = VK_NULL_HANDLE;
  VmaAllocation StagingAlloc = VK_NULL_HANDLE;
  void *StagingMapped = nullptr;
  if (!i8AllocateStagingBuffer(Allocator, Width,
                               VK_BUFFER_USAGE_TRANSFER_SRC_BIT, Staging,
                               StagingAlloc, StagingMapped))
    CHIPERR_LOG_AND_THROW("memFillAsync3D: failed to allocate staging buffer",
                          hipErrorOutOfMemory);
  unsigned char Byte = static_cast<unsigned char>(Value);
  std::memset(StagingMapped, Byte, Width);

  std::vector<VkBufferCopy> Regions;
  Regions.reserve(Depth * Height);
  for (size_t S = 0; S < Depth; ++S)
    for (size_t R = 0; R < Height; ++R) {
      VkBufferCopy Reg{};
      Reg.srcOffset = 0;
      Reg.dstOffset = DstOffset + S * SlicePitch + R * Pitch;
      Reg.size = Width;
      Regions.push_back(Reg);
    }
  vkCmdCopyBuffer(Cmd, Staging, DstBuf, static_cast<uint32_t>(Regions.size()),
                  Regions.data());
  i8EndCmdBuffer(Cmd);
  auto Ev = submitWithEvent(Cmd, {});
  i8RecordPendingStaging(Allocator, Staging, StagingAlloc, Ev);
  Ev->Msg = "memFillAsync3D";
}

// ============================================================================
// ===== I7: =====
// ============================================================================
//
// launchImpl is the integration point: take a fully-built CHIPExecItemVulkan
// (push-constant blob + per-binding VkBuffer list already populated by I4's
// setupAllArgs, which the framework runs before us in
// chipstar::Queue::launchKernel), bind the pipeline + descriptor set + push
// constants for the kernel, record a vkCmdDispatch, and submit through I6's
// submitWithEvent helper. The returned shared_ptr<chipstar::Event> is
// surfaced back through chipstar::Queue::launch() to HIP land.
//
// Descriptor-pool strategy:
//   The pool is per-queue and created lazily on first launch. We keep the
//   per-queue pool in a file-static map (not on CHIPQueueVulkan_ - the .hh
//   is frozen for the parallel-implementer phase) keyed by queue pointer.
//   The pool is sized generously for the spike (1024 sets, 32K storage
//   buffer descriptors) and is never freed in this section; queue teardown
//   (I6) is responsible for destroying it. We do NOT enable
//   VK_DESCRIPTOR_POOL_CREATE_FREE_DESCRIPTOR_SET_BIT; sets are recycled
//   wholesale by vkResetDescriptorPool on Queue::finish.
//
// Lifetime tracking:
//   Allocated descriptor sets remain valid until the GPU finishes the
//   submit that consumed them. For the spike we delegate cleanup to
//   Queue::finish() (I6), which calls vkResetDescriptorPool after waiting
//   on outstanding fences. A future polish pass can swap this for a
//   per-event free-list once event lifetime callbacks are wired up.

namespace {

struct VulkanQueueDescriptorPool {
  VkDescriptorPool Pool = VK_NULL_HANDLE;
  VkDevice Device = VK_NULL_HANDLE;
};

// Per-queue descriptor pools. Lazy-created on first launch; destroyed by I6
// at queue teardown. Guarded by a single mutex - contention is negligible
// because every queue keys to a distinct entry.
std::unordered_map<CHIPQueueVulkan *, VulkanQueueDescriptorPool>
    GVkQueueDescriptorPools;
std::mutex GVkQueueDescriptorPoolsMtx;

// Pool sizing constants. Chosen for the spike: ample headroom for the
// vecadd-style kernels we ship out of the gate, while staying well under
// typical driver maxima.
constexpr uint32_t kDescPoolMaxSets = 1024;
constexpr uint32_t kDescPoolMaxStorageBuffers = 32 * 1024;

VkDescriptorPool getOrCreateQueueDescriptorPool(CHIPQueueVulkan *Queue,
                                                VkDevice Device) {
  std::lock_guard<std::mutex> Lock(GVkQueueDescriptorPoolsMtx);
  auto &Slot = GVkQueueDescriptorPools[Queue];
  if (Slot.Pool != VK_NULL_HANDLE)
    return Slot.Pool;

  VkDescriptorPoolSize PoolSize{};
  PoolSize.type = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
  PoolSize.descriptorCount = kDescPoolMaxStorageBuffers;

  VkDescriptorPoolCreateInfo PoolInfo{};
  PoolInfo.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO;
  PoolInfo.maxSets = kDescPoolMaxSets;
  PoolInfo.poolSizeCount = 1;
  PoolInfo.pPoolSizes = &PoolSize;
  // No FREE_DESCRIPTOR_SET_BIT: sets are recycled wholesale via
  // vkResetDescriptorPool on Queue::finish (I6).

  VkResult R =
      vkCreateDescriptorPool(Device, &PoolInfo, nullptr, &Slot.Pool);
  if (R != VK_SUCCESS || Slot.Pool == VK_NULL_HANDLE) {
    CHIPERR_LOG_AND_THROW("vkCreateDescriptorPool failed in launchImpl",
                          hipErrorOutOfMemory);
  }
  Slot.Device = Device;
  return Slot.Pool;
}

} // namespace

std::shared_ptr<chipstar::Event>
CHIPQueueVulkan::launchImpl(chipstar::ExecItem *ExecItem) {
  // The framework (chipstar::Queue::launchKernel in src/CHIPBackend.cc and
  // related call sites) has already invoked ExecItem->setupAllArgs() before
  // we get here, so PushConstantBlob_ and BufferBindings_ are populated.
  auto CmdLock = lockCmdRecord();
  if (!ExecItem)
    CHIPERR_LOG_AND_THROW("CHIPQueueVulkan::launchImpl received null ExecItem",
                          hipErrorInvalidValue);

  auto *VkExecItem = static_cast<CHIPExecItemVulkan *>(ExecItem);
  auto *Kernel =
      static_cast<CHIPKernelVulkan *>(VkExecItem->getVulkanKernel());
  if (!Kernel)
    CHIPERR_LOG_AND_THROW(
        "CHIPQueueVulkan::launchImpl: ExecItem has no kernel bound",
        hipErrorInvalidValue);

  auto *Module = Kernel->getVulkanModule();
  if (!Module)
    CHIPERR_LOG_AND_THROW(
        "CHIPQueueVulkan::launchImpl: kernel has no parent module",
        hipErrorInvalidValue);

  const std::string KernelName = Kernel->getName();
  const VulkanKernelReflection *Refl = Module->getReflection(KernelName);
  if (!Refl)
    CHIPERR_LOG_AND_THROW(
        "CHIPQueueVulkan::launchImpl: no reflection record for kernel",
        hipErrorInvalidValue);

  // Z6: refuse oversized push-constant launches cleanly. Bypassing this
  // guard (e.g. by stripping the flag) drops the dispatch into UB inside
  // VkCmdPushConstants and segfaults the driver. Lowering the spill to a
  // UBO is a future bridging-pass feature.
  if (Refl->OversizedPushConstants)
    CHIPERR_LOG_AND_THROW(
        "CHIPQueueVulkan::launchImpl: kernel push-constant block exceeds "
        "VkPhysicalDeviceLimits::maxPushConstantsSize; UBO spill not yet "
        "implemented",
        hipErrorNotSupported);

  dim3 Grid = VkExecItem->getGrid();
  dim3 Block = VkExecItem->getBlock();
  VkPipeline Pipeline = Module->getOrCreatePipeline(KernelName, Block);
  VkDescriptorSetLayout DSLayout =
      Module->getOrCreateDescriptorSetLayout(KernelName);
  VkPipelineLayout PLLayout = Module->getOrCreatePipelineLayout(KernelName);
  if (Pipeline == VK_NULL_HANDLE || PLLayout == VK_NULL_HANDLE)
    CHIPERR_LOG_AND_THROW(
        "CHIPQueueVulkan::launchImpl: failed to build pipeline / layout",
        hipErrorInvalidValue);

  VkDevice Device = ChipDevice_->getLogicalDevice();

  // ---- Allocate the descriptor set from the per-queue pool. ----
  VkDescriptorPool DescPool = getOrCreateQueueDescriptorPool(this, Device);
  VkDescriptorSet DescSet = VK_NULL_HANDLE;
  {
    VkDescriptorSetAllocateInfo AllocInfo{};
    AllocInfo.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO;
    AllocInfo.descriptorPool = DescPool;
    AllocInfo.descriptorSetCount = 1;
    AllocInfo.pSetLayouts = &DSLayout;
    VkResult R = vkAllocateDescriptorSets(Device, &AllocInfo, &DescSet);
    if (R == VK_ERROR_OUT_OF_POOL_MEMORY || R == VK_ERROR_FRAGMENTED_POOL) {
      // Pool exhausted: once this queue's submitted work (the only user of
      // its pool) has finished, every set can be recycled.
      uint64_t Target;
      {
        std::lock_guard<std::mutex> Lock(QueueOpMtx_);
        Target = TimelineValue_;
      }
      VkSemaphoreWaitInfo WI{};
      WI.sType = VK_STRUCTURE_TYPE_SEMAPHORE_WAIT_INFO;
      WI.semaphoreCount = 1;
      WI.pSemaphores = &TimelineSemaphore_;
      WI.pValues = &Target;
      vkWaitSemaphores(Device, &WI, UINT64_MAX);
      vkResetDescriptorPool(Device, DescPool, 0);
      DescSet = VK_NULL_HANDLE;
      R = vkAllocateDescriptorSets(Device, &AllocInfo, &DescSet);
    }
    if (R != VK_SUCCESS || DescSet == VK_NULL_HANDLE)
      CHIPERR_LOG_AND_THROW("vkAllocateDescriptorSets failed in launchImpl",
                            hipErrorOutOfMemory);
  }

  // ---- Populate the descriptor set from the (binding, VkBuffer) list. ----
  const auto &Bindings = VkExecItem->getBufferBindings();
  const auto &Ranges = VkExecItem->getBufferRanges();
  const auto &Offsets = VkExecItem->getBufferOffsets();
  if (Bindings.size() != Ranges.size() || Bindings.size() != Offsets.size())
    CHIPERR_LOG_AND_THROW(
        "CHIPQueueVulkan::launchImpl: BufferBindings/Ranges/Offsets size mismatch",
        hipErrorInvalidValue);

  std::vector<VkDescriptorBufferInfo> BufInfos;
  std::vector<VkWriteDescriptorSet> Writes;
  BufInfos.reserve(Bindings.size());
  Writes.reserve(Bindings.size());
  for (uint32_t I = 0; I < Bindings.size(); ++I) {
    VkBuffer Buf = Bindings[I];
    if (Buf == VK_NULL_HANDLE)
      continue; // Sparse binding slot - leave the descriptor unbound. I7
                // does not fail here because the bridging-pass guarantees
                // the kernel won't dereference unbound slots. A future
                // strict-mode polish can flip this to a hard error.
    VkDescriptorBufferInfo &BI = BufInfos.emplace_back();
    BI.buffer = Buf;
    BI.offset = Offsets[I];
    BI.range = Ranges[I] == 0 ? VK_WHOLE_SIZE : Ranges[I];

    VkWriteDescriptorSet &W = Writes.emplace_back();
    W = {};
    W.sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
    W.dstSet = DescSet;
    W.dstBinding = I;
    W.dstArrayElement = 0;
    W.descriptorCount = 1;
    W.descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
    W.pBufferInfo = &BI;
  }
  if (!Writes.empty())
    vkUpdateDescriptorSets(Device, static_cast<uint32_t>(Writes.size()),
                           Writes.data(), 0, nullptr);

  // ---- Record the command buffer. ----
  VkCommandBuffer Cmd = acquireCmdBuffer();
  if (Cmd == VK_NULL_HANDLE)
    CHIPERR_LOG_AND_THROW(
        "CHIPQueueVulkan::launchImpl: acquireCmdBuffer returned null",
        hipErrorTbd);

  VkCommandBufferBeginInfo BeginInfo{};
  BeginInfo.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
  BeginInfo.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
  if (vkBeginCommandBuffer(Cmd, &BeginInfo) != VK_SUCCESS)
    CHIPERR_LOG_AND_THROW("vkBeginCommandBuffer failed in launchImpl",
                          hipErrorTbd);

  vkCmdBindPipeline(Cmd, VK_PIPELINE_BIND_POINT_COMPUTE, Pipeline);
  vkCmdBindDescriptorSets(Cmd, VK_PIPELINE_BIND_POINT_COMPUTE, PLLayout,
                          /*firstSet=*/0, 1, &DescSet,
                          /*dynamicOffsetCount=*/0, nullptr);

  const auto &PCBlob = VkExecItem->getPushConstantBlob();
  if (Refl->PushConstantBlockSize > 0 && !PCBlob.empty()) {
    // We honor the reflection's size - the blob may be larger if the I4
    // packer rounds up; the kernel only reads up to PushConstantBlockSize.
    const uint32_t PCSize =
        std::min<uint32_t>(Refl->PushConstantBlockSize,
                           static_cast<uint32_t>(PCBlob.size()));
    vkCmdPushConstants(Cmd, PLLayout, VK_SHADER_STAGE_COMPUTE_BIT,
                       /*offset=*/0, PCSize, PCBlob.data());
  }

  vkCmdDispatch(Cmd, Grid.x, Grid.y, Grid.z);

  if (vkEndCommandBuffer(Cmd) != VK_SUCCESS)
    CHIPERR_LOG_AND_THROW("vkEndCommandBuffer failed in launchImpl",
                          hipErrorTbd);

  IsEmptyQueue_.store(false);

  // ---- Submit. I6's helper owns event creation + tracking + wait list. ----
  std::vector<std::shared_ptr<chipstar::Event>> NoWaits;
  std::shared_ptr<chipstar::Event> LaunchEvent =
      submitWithEvent(Cmd, NoWaits);
  if (LaunchEvent)
    LaunchEvent->Msg = "KernelLaunch";
  return LaunchEvent;
}

