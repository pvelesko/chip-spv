// Backed by a VkFence (Fence_) for completion tracking and an optional slot in
// the device-wide VkQueryPool of TIMESTAMP queries (TimestampSlot_) for GPU-
// side elapsed-time measurement. When timing is disabled
// (hipEventDisableTiming) the slot stays -1 and getElapsedTime() falls back to
// the chrono::steady_clock-derived HostTimestamp_ captured in
// updateFinishStatus()/wait() at fence-completion time.
//
// Timestamp scaling formula:
//   raw   = vkGetQueryPoolResults(slot)            // 64-bit ticks
//   mask  = UINT64_MAX (full 64-bit) — see note in getElapsedTime()
//   ticks = raw & mask
//   ns    = ticks * timestampPeriod                // ns per tick, from
//                                                  // VkPhysicalDeviceLimits
// (mirrors the Level0 backend's getFinishTime() pattern.)
//
// hostSignal: Vulkan exposes no host-signal-fence API analogous to
// zeEventHostSignal / clSetUserEventStatus. A correct implementation would
// wrap a binary semaphore + host worker, but that is out of scope for the
// H4 spike, so we surface hipErrorNotSupported here.

CHIPEventVulkan::CHIPEventVulkan(chipstar::Context *Ctx,
                                 chipstar::EventFlags Flags)
    : chipstar::Event(Ctx, Flags) {
  Fence_ = VK_NULL_HANDLE;
  TimestampSlot_ = -1;
  HostTimestamp_ = 0;
  Timestamp_ = UINT64_MAX;

  // Acquire a VkFence from the device pool on construction. Without a per-
  // event fence, submitWithEvent falls back to a queue-wide shared fence
  // that gets reset on every submit, and the I8 staging-buffer reclaim path
  // (which checks Ev->getFence() to decide if the GPU is done) sees a null
  // fence, treats every staging as "done", and frees buffers while the GPU
  // is still reading from them. That manifests as cross-allocation H2D
  // data shifting (each new H2D appears to land in the previous buffer).
  if (Ctx) {
    auto *VkCtx = static_cast<CHIPContextVulkan *>(Ctx);
    if (auto *Dev = VkCtx->getVulkanDevice()) {
      Fence_ = Dev->acquireFence();
    }
  }
}

CHIPEventVulkan::~CHIPEventVulkan() {
  // Return our fence + timestamp slot to the owning device's recycle pools.
  // ChipContext_ may be null in obscure teardown orderings; guard accordingly.
  if (ChipContext_) {
    auto *VkCtx = static_cast<CHIPContextVulkan *>(ChipContext_);
    if (auto *Dev = VkCtx->getVulkanDevice()) {
      if (Fence_ != VK_NULL_HANDLE) {
        Dev->releaseFence(Fence_);
        Fence_ = VK_NULL_HANDLE;
      }
      if (TimestampSlot_ >= 0) {
        Dev->releaseTimestampSlot(TimestampSlot_);
        TimestampSlot_ = -1;
      }
    }
  }
}

bool CHIPEventVulkan::updateFinishStatus(bool ThrowErrorIfNotReady) {
  isDeletedSanityCheck();

  // Per the base-class contract: only events that are currently in the
  // RECORDING state can transition to RECORDED here. Already-recorded events
  // are no-ops; INIT events have no pending GPU work to query against.
  if (EventStatus_ != EVENT_STATUS_RECORDING)
    return false;

  auto *VkCtx = static_cast<CHIPContextVulkan *>(ChipContext_);
  auto *Dev = VkCtx ? VkCtx->getVulkanDevice() : nullptr;
  if (!Dev || Fence_ == VK_NULL_HANDLE) {
    // Recording but no fence to query - treat as not-ready.
    if (ThrowErrorIfNotReady)
      CHIPERR_LOG_AND_THROW("Vulkan event has no fence to query",
                            hipErrorNotReady);
    return false;
  }

  VkResult Status = vkGetFenceStatus(Dev->getLogicalDevice(), Fence_);
  if (Status == VK_SUCCESS) {
    EventStatus_ = EVENT_STATUS_RECORDED;
    // Capture host-side fallback timestamp at completion-observed time.
    HostTimestamp_ = static_cast<uint64_t>(
        std::chrono::duration_cast<std::chrono::nanoseconds>(
            std::chrono::steady_clock::now().time_since_epoch())
            .count());
    releaseDependencies();
    return true;
  }
  if (Status == VK_NOT_READY) {
    if (ThrowErrorIfNotReady)
      CHIPERR_LOG_AND_THROW("chipstar::Event Not Ready", hipErrorNotReady);
    return false;
  }
  // Device-lost or other hard failures.
  CHIPERR_LOG_AND_THROW("vkGetFenceStatus returned a hard error",
                        hipErrorTbd);
}

bool CHIPEventVulkan::wait() {
  isDeletedSanityCheck();

  // Already-finished events return immediately.
  if (EventStatus_ == EVENT_STATUS_RECORDED)
    return true;

  auto *VkCtx = static_cast<CHIPContextVulkan *>(ChipContext_);
  auto *Dev = VkCtx ? VkCtx->getVulkanDevice() : nullptr;
  if (!Dev || Fence_ == VK_NULL_HANDLE ||
      EventStatus_ == EVENT_STATUS_INIT) {
    // No fence to wait on (e.g. INIT-state user event with no GPU work).
    // Mark RECORDED to match Level0/OpenCL behavior for empty events.
    // Critically, if the event is still in INIT (never recorded against a
    // queue) the fence is unsignaled and vkWaitForFences would hang.
    LOCK(EventMtx);
    EventStatus_ = EVENT_STATUS_RECORDED;
    return true;
  }

  VkResult Status =
      vkWaitForFences(Dev->getLogicalDevice(), 1, &Fence_, VK_TRUE, UINT64_MAX);
  if (Status != VK_SUCCESS) {
    CHIPERR_LOG_AND_THROW("vkWaitForFences failed", hipErrorTbd);
  }

  {
    LOCK(EventMtx); // chipstar::Event::EventStatus_
    EventStatus_ = EVENT_STATUS_RECORDED;
    HostTimestamp_ = static_cast<uint64_t>(
        std::chrono::duration_cast<std::chrono::nanoseconds>(
            std::chrono::steady_clock::now().time_since_epoch())
            .count());
  }
  releaseDependencies();
  return true;
}

float CHIPEventVulkan::getElapsedTime(chipstar::Event *OtherIn) {
  auto *Other = static_cast<CHIPEventVulkan *>(OtherIn);

  if (this->getContext() != Other->getContext())
    CHIPERR_LOG_AND_THROW(
        "Attempted to get elapsed time between two events that are not part "
        "of the same context",
        hipErrorTbd);

  // Best-effort status refresh; both events must be RECORDED to read a
  // meaningful timestamp. Mirrors the Level0/OpenCL flow.
  if (this->getEventStatus() == EVENT_STATUS_RECORDING)
    this->updateFinishStatus(false);
  if (Other != this && Other->getEventStatus() == EVENT_STATUS_RECORDING)
    Other->updateFinishStatus(false);

  if (!this->isFinished() || !Other->isFinished())
    CHIPERR_LOG_AND_THROW("one of the events hasn't finished",
                          hipErrorNotReady);

  auto *VkCtx = static_cast<CHIPContextVulkan *>(ChipContext_);
  auto *Dev = VkCtx ? VkCtx->getVulkanDevice() : nullptr;

  // Helper: read one timestamp-pool slot (raw ticks). Returns false if the
  // slot is invalid or the query result is unavailable. Fence already
  // signaled, so VK_QUERY_RESULT_WAIT_BIT should be a formality.
  auto readSlot = [&](int32_t Slot, uint64_t &OutTicks) -> bool {
    if (!Dev || Slot < 0 || Dev->getTimestampQueryPool() == VK_NULL_HANDLE)
      return false;
    uint64_t Raw = 0;
    VkResult R = vkGetQueryPoolResults(
        Dev->getLogicalDevice(), Dev->getTimestampQueryPool(),
        static_cast<uint32_t>(Slot), /*queryCount=*/1, sizeof(Raw), &Raw,
        sizeof(Raw),
        VK_QUERY_RESULT_64_BIT | VK_QUERY_RESULT_WAIT_BIT);
    if (R != VK_SUCCESS)
      return false;
    OutTicks = Raw;
    return true;
  };

  uint64_t StartedNs = 0;
  uint64_t FinishedNs = 0;
  bool HaveGpuStart = false, HaveGpuEnd = false;

  if (Dev) {
    uint64_t StartTicks = 0, EndTicks = 0;
    const auto &Limits = Dev->getProperties().limits;
    // Per Vulkan spec, timestampValidBits lives on VkQueueFamilyProperties,
    // not VkPhysicalDeviceLimits. The Device-level Properties_ exposed here
    // is the physical-device-property record, so we use the conservative
    // full 64-bit mask. Wrap-around on devices with fewer valid bits is
    // tolerable for the spike: modern GPUs report 64 valid bits, and the
    // elapsed-time math below uses unsigned subtraction so a single wrap
    // still yields a positive elapsed value (with absolute time meaningless
    // on its own, only the delta matters). I1 may later store per-queue
    // queueFamilyProperties.timestampValidBits and expose it; for now skip.
    const uint64_t Mask = UINT64_MAX;
    // VkPhysicalDeviceLimits::timestampPeriod is the ns-per-tick scale.
    const double Period = static_cast<double>(Limits.timestampPeriod);

    if (readSlot(this->TimestampSlot_, StartTicks)) {
      Timestamp_ = static_cast<uint64_t>(
          static_cast<double>(StartTicks & Mask) * Period);
      StartedNs = Timestamp_;
      HaveGpuStart = true;
    }
    if (readSlot(Other->TimestampSlot_, EndTicks)) {
      Other->Timestamp_ = static_cast<uint64_t>(
          static_cast<double>(EndTicks & Mask) * Period);
      FinishedNs = Other->Timestamp_;
      HaveGpuEnd = true;
    }
  }

  // Fallback path: timing disabled on at least one side, or query pool
  // unavailable. Use the chrono::steady_clock stamps captured at
  // fence-completion time. Coarse but lets hipEventElapsedTime return
  // something sensible instead of throwing.
  if (!HaveGpuStart || !HaveGpuEnd) {
    StartedNs = this->HostTimestamp_;
    FinishedNs = Other->HostTimestamp_;
  }

  // OpenCL-style elapsed-time math: handle reversed order, convert to ms
  // with explicit fractional precision (avoids float64->float32 loss for
  // multi-second elapsed values).
  bool Reversed = false;
  uint64_t Begin = StartedNs;
  uint64_t End = FinishedNs;
  if (End < Begin) {
    Reversed = true;
    std::swap(Begin, End);
  }
  int64_t ElapsedNs = static_cast<int64_t>(End - Begin);

  constexpr int64_t NsPerSec = 1000000000;
  int64_t WholeMs = (ElapsedNs / NsPerSec) * 1000;
  int64_t FracNs = ElapsedNs % NsPerSec;
  float FracMs = static_cast<float>(FracNs) / 1000000.0f;
  float Ms = static_cast<float>(WholeMs) + FracMs;
  if (Reversed)
    Ms = -Ms;
  return Ms;
}

void CHIPEventVulkan::hostSignal() {
  isDeletedSanityCheck();
  // Vulkan has no host-signal-fence primitive (no zeEventHostSignal /
  // clSetUserEventStatus analogue in core 1.2). The chipstar callback path
  // uses hostSignal() on the "CpuCallbackComplete" event to mark it RECORDED
  // from the host so any host-side wait() returns. On Vulkan, our callback
  // chain (EventMonitor below) does not block GPU work on this event — the
  // monitor host-waits on GpuReady's fence, runs the user callback, then
  // host-signals CpuCallbackComplete. Marking the event RECORDED here is
  // sufficient to unblock concurrent wait() callers and the EventMonitor's
  // recycle pass. wait() short-circuits on EVENT_STATUS_RECORDED before
  // touching the (unsignaled) fence.
  LOCK(EventMtx);
  EventStatus_ = EVENT_STATUS_RECORDED;
  HostTimestamp_ = static_cast<uint64_t>(
      std::chrono::duration_cast<std::chrono::nanoseconds>(
          std::chrono::steady_clock::now().time_since_epoch())
          .count());
}
// ============================================================================
// ===== I11: CHIPCallbackDataVulkan
// ============================================================================
//
// Build the GpuReady/CpuCallbackComplete/GpuAck triplet the EventMonitor
// callback drainer expects. Unlike Level0, the Vulkan flow does not chain
// the CPU/GPU ack through a GPU-side barrier (Vulkan has no
// vkCommandBufferAppendBarrier-on-binary-event primitive that participates
// in submit ordering). Instead the EventMonitor host-waits on GpuReady's
// fence, runs the user callback, host-signals CpuCallbackComplete, and
// host-signals GpuAck. The "GpuAck" semantics still work because nothing
// in the spike currently uses GpuAck as a wait-dep for a GPU operation;
// it only blocks the EventMonitor's per-callback drain step.

static thread_local bool InCallbackThread = false;

CHIPCallbackDataVulkan::CHIPCallbackDataVulkan(hipStreamCallback_t CallbackF,
                                                void *CallbackArgs,
                                                chipstar::Queue *ChipQueue)
    : chipstar::CallbackData(CallbackF, CallbackArgs, ChipQueue) {
  static_cast<CHIPQueueVulkan *>(ChipQueue)->PendingCallbacks++;
  auto *Ctx = ChipQueue->getContext();
  auto *BVk = static_cast<CHIPBackendVulkan *>(Backend);

  // GpuReady: marker enqueued on the queue. Its fence signals when the
  // command stream reaches the callback insertion point.
  GpuReady = ChipQueue->enqueueMarkerImpl();
  if (GpuReady) {
    GpuReady->Msg = "CallbackGpuReady";
    // Track so the EventMonitor's recycle pass leaves it alive until the
    // callback drains; the drain step erases via the CallbackQueue path.
    Backend->trackEvent(GpuReady);
  }

  // CpuCallbackComplete + GpuAck: host-only signaling events. Created
  // through the backend so they participate in the same fence-pool /
  // tracking infrastructure as GPU events.
  CpuCallbackComplete = BVk->createEventShared(Ctx, chipstar::EventFlags(),
                                                "CallbackCpuComplete");
  GpuAck = BVk->createEventShared(Ctx, chipstar::EventFlags(), "CallbackGpuAck");
}

